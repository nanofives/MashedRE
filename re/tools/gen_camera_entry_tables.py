"""Generate mashedmod/src/mashed_re/Race/CameraEntryTables.h from original/MASHED.exe.unpatched.

FUN_00442600's 13 per-track entry tables (switch 0x0044261b..0x0044268f). They are file-backed .data,
which the standalone exe maps zero-filled, so the exe arm embeds them. Layout: float count, then count
rows of 12 dwords (0x30 B). Re-run if the anchor changes.
"""
import struct, pefile
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
pe = pefile.PE(str(ROOT / "original/MASHED.exe.unpatched")); ib = pe.OPTIONAL_HEADER.ImageBase
TABLES = [(2, 0x5f91e0), (3, 0x5f7e48), (0xb, 0x5f9368), (0x19, 0x5f8980), (0x1a, 0x5f8490), (0x1e, 0x5f8d50),
          (0x21, 0x5f7bd0), (0x22, 0x5f8798), (0x24, 0x5f8b68), (0x25, 0x5f8ea8), (0x26, 0x5f8030),
          (0x27, 0x5f7a48), (-1, 0x5f82a8)]          # -1 = default arm
out = ["// GENERATED by re/tools/gen_camera_entry_tables.py from original/MASHED.exe.unpatched. Do not edit.",
       "// FUN_00442600's per-track camera-entry tables (switch at 0x0044261b). Dwords as in the image.",
       "#pragma once", "#include <cstdint>", "namespace mashed_re { namespace CamEntry {"]
names = []
for tid, va in TABLES:
    n = int(struct.unpack('<f', pe.get_data(va - ib, 4))[0])
    words = struct.unpack('<%dI' % (1 + 12 * n), pe.get_data(va - ib, 4 + 0x30 * n))
    nm = "kTable_%06x" % va; names.append((tid, va, nm, n))
    body = ", ".join("0x%08xu" % w for w in words)
    out.append("static const std::uint32_t %s[%d] = { %s };   // 0x%08x, %d rows" % (nm, len(words), body, va, n))
out.append("struct TableRef { int track; std::uint32_t va; const std::uint32_t* words; };")
out.append("static const TableRef kTables[%d] = {" % len(names))
for tid, va, nm, n in names:
    out.append("    { %d, 0x%08xu, %s }," % (tid, va, nm))
out.append("};")
out.append("} }")
dst = ROOT / "mashedmod/src/mashed_re/Race/CameraEntryTables.h"
dst.write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote", dst, [(hex(t), n) for t, _, _, n in names])
