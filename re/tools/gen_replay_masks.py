"""Generate re/frida/replay_masks.tsv (RO-MASKS, 2026-11-13): the per-dword mask file for the exe-vs-original compare.

Two inputs, one output:
  1. bound families at ADDRESS level: every .text instruction with an absolute memory operand (base none) inside
     0x005ea000..0x00915008 is attributed to its function (Ghidra facts) and the function to its hooks.csv subsystem
     (the same attribution as verify/replayoracle_20261111/data_owner_map.py, kept per address instead of per page).
     A dword is masked when EVERY function that references it belongs to the same bound family (the exe replaces that
     code: CRT, RenderWare core, d3dx9, directshow, qhull, lua, audio). A dword also referenced by a game-code family
     is NOT masked and is listed in the shared report (--shared). Pointer-register bases are not seen (static scan).
  2. re/frida/replay_masks_manual.tsv: OS words, stale-stack fields, boot residue, each with address and reason.

Output rows use the warp_normalize.tsv columns, so detorig.load_norm reads them. Run from the repo root:
    py -3.12 re/tools/gen_replay_masks.py [--facts <ghidra_funcfacts.jsonl>] [--shared <tsv>]
"""
import argparse, bisect, csv, json, pathlib, sys
from collections import defaultdict

import capstone
import pefile

ROOT = pathlib.Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "re" / "tools"))
import xref  # noqa: E402

LO, HI = 0x005ea000, 0x00915008
# hooks.csv subsystem prefix -> mask family name.
BOUND = [("third-party-library[msvc-crt", "crt"), ("third-party-library[msvc-seh", "crt"),
         ("third-party-library[renderware]", "renderware"), ("third-party-library[d3dx9", "d3dx9"),
         ("third-party-library[directshow", "directshow"), ("third-party-library[qhull", "qhull"),
         ("third-party-library[lua", "lua"), ("audio", "audio")]


def bound_name(sub):
    for pre, name in BOUND:
        if sub == pre or sub.startswith(pre):
            return name
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--facts", default="")
    ap.add_argument("--shared", default="")
    ap.add_argument("--out", default=str(ROOT / "re" / "frida" / "replay_masks.tsv"))
    a = ap.parse_args()
    facts = pathlib.Path(a.facts) if a.facts else xref.FACTS
    fam = {}
    for r in csv.DictReader(l for l in open(ROOT / "hooks.csv", encoding="utf-8") if not l.startswith("#")):
        try:
            fam[int(r["rva"], 16)] = r["subsystem"] or "?"
        except (ValueError, KeyError, TypeError):
            pass
    funcs = []
    for line in open(facts):
        r = json.loads(line)
        if "entry" in r:
            for lo, hi in r["ranges"]:
                funcs.append((int(lo, 16), int(hi, 16), int(r["entry"], 16)))
    funcs.sort()
    starts = [f[0] for f in funcs]

    def owner(va):
        i = bisect.bisect_right(starts, va) - 1
        while i >= 0:
            if funcs[i][0] <= va <= funcs[i][1]:
                return funcs[i][2]
            if va - funcs[i][0] > 0x40000:
                break
            i -= 1
        return None

    pe = pefile.PE(str(xref.EXE))
    base = pe.OPTIONAL_HEADER.ImageBase
    text = next(s for s in pe.sections if s.Name.rstrip(b"\0") == b".text")
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail = True
    md.skipdata = True
    refs = defaultdict(set)   # dword-aligned va -> {subsystem}
    for ins in md.disasm(text.get_data(), base + text.VirtualAddress):
        if ins.id == 0:
            continue
        for op in ins.operands:
            if op.type == capstone.x86.X86_OP_MEM and op.mem.base == 0:
                d = op.mem.disp & 0xffffffff
                if LO <= d < HI:
                    f = owner(ins.address)
                    refs[d & ~3].add(fam.get(f, "no-hooks-row") if f else "no-function")
    masked = {}
    shared = []
    for d, subs in refs.items():
        names = {bound_name(s) for s in subs}
        if None not in names and len(names) == 1:
            masked[d] = names.pop()
        elif None in names and len(names) > 1:
            shared.append((d, sorted(subs)))
    spans = []   # coalesce consecutive dwords of one family
    for d in sorted(masked):
        if spans and spans[-1][2] == masked[d] and spans[-1][0] + spans[-1][1] == d:
            spans[-1][1] += 4
        else:
            spans.append([d, 4, masked[d]])
    man = ROOT / "re" / "frida" / "replay_masks_manual.tsv"
    out = ["# Per-dword mask file for the exe-vs-original compare (RO-MASKS, 2026-11-13). GENERATED by re/tools/gen_replay_masks.py:",
           "# do not hand-edit, edit re/frida/replay_masks_manual.tsv and regenerate. Columns as in warp_normalize.tsv (detorig.load_norm).",
           "# MASK:<family> = the compare drops the dword. Section 1: bound families at address level (every referencing function is",
           "# in the family; %d dwords in %d spans). Section 2: replay_masks_manual.tsv rows (OS words, stale stack, residue)." % (len(masked), len(spans)),
           "va\tcount\tstride\twidth\taction\tvalue\twriter\treaders\tnote"]
    for lo, w, f in spans:
        out.append(f"0x{lo:08x}\t1\t0\t{w}\tMASK:{f}\t-\tbound family\t-\tevery absolute-operand referrer is {f} code")
    for line in open(man, encoding="utf-8"):
        if line.strip() and not line.startswith("#") and not line.startswith("va\t"):
            out.append(line.rstrip("\n"))
    pathlib.Path(a.out).write_text("\n".join(out) + "\n", encoding="utf-8")
    cnt = defaultdict(int)
    for f in masked.values():
        cnt[f] += 1
    print("masked dwords by family:", dict(cnt), "spans", len(spans), "shared (bound + game code, not masked):", len(shared))
    if a.shared:
        with open(a.shared, "w", encoding="utf-8") as fh:
            fh.write("va\tsubsystems\n")
            for d, s in sorted(shared):
                fh.write(f"0x{d:08x}\t{'; '.join(s)}\n")


if __name__ == "__main__":
    main()
