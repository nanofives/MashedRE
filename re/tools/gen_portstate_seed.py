#!/usr/bin/env python3
"""Generate / check the port-state seed table (PORT-STATE-02, decision L-99 option (a)).

The exe's image pad (exe_main.cpp B17, g_b17_low_arena_pad) owns the original's address range zero-filled, so a
matched body that reads a file-backed .rdata / .data value of the original reads 0 in mashed_re.exe. This tool
reads those values from original/MASHED.exe.unpatched for exactly the addresses of the inventory
(verify/portstate_20261108/SEED_CANDIDATES.tsv, generated by that folder's inventory.py) and writes the committed
table mashedmod/src/mashed_re/Compat/PortStateSeed.inc. The exe copies it into the pad at WinMain entry when
MASHED_PORTSTATE_SEED is set (Compat/PortStateSeed.cpp).

  py -3.12 re/tools/gen_portstate_seed.py            # (re)write the .inc
  py -3.12 re/tools/gen_portstate_seed.py --check    # lint: the .inc == the inventory == the binary

Refusals (exit 1): the binary's SHA-256 is not the anchor; an address maps to no section, or to the
uninitialized tail of a section (no file bytes); two inventory ranges overlap; a string entry whose last byte
is not NUL in the file (the entry would cut the string).

--check exits 1 when the .inc's address list differs from the inventory, its bytes differ from the binary,
or its recorded FNV-1a differs from the one recomputed from its own arrays. Without the binary (a git-archive
build such as the LAN release) the binary leg is skipped and said so; without the inventory the whole check is
skipped and said so (exit 0).

FNV-1a 32 is taken over the entries in address order, each serialized as addr (u32 LE), len (u32 LE), bytes.
"""
import argparse
import hashlib
import os
import re
import struct
import subprocess
import sys

ANCHOR = 'BDCAE093A30FBF226BDD852B9C36798A987AEE33B3AE82BF7404B0336EFD3C0E'
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..'))
INV_DEFAULT = os.path.join(REPO, 'verify', 'portstate_20261108', 'SEED_CANDIDATES.tsv')
OUT_DEFAULT = os.path.join(REPO, 'mashedmod', 'src', 'mashed_re', 'Compat', 'PortStateSeed.inc')


def find_unpatched():
    env = os.environ.get('MASHED_UNPATCHED')
    if env:
        return env
    cands = [os.path.join(REPO, 'original', 'MASHED.exe.unpatched')]
    root = os.environ.get('MASHED_ROOT')
    if root:
        cands.append(os.path.join(root, 'original', 'MASHED.exe.unpatched'))
    try:   # a worktree: the main checkout holds original/
        common = subprocess.run(['git', '-C', REPO, 'rev-parse', '--git-common-dir'], capture_output=True,
                                text=True, check=True).stdout.strip()
        if not os.path.isabs(common):
            common = os.path.join(REPO, common)
        cands.append(os.path.join(os.path.dirname(os.path.normpath(common)), 'original', 'MASHED.exe.unpatched'))
    except Exception:
        pass
    for c in cands:
        if os.path.isfile(c):
            return c
    return None


def pe_sections(raw):
    """(name, va, vsize, rawsize, rawptr) from the PE headers; field order per the PE spec."""
    e_lfanew = struct.unpack_from('<I', raw, 0x3c)[0]
    assert raw[e_lfanew:e_lfanew + 4] == b'PE\0\0'
    nsec = struct.unpack_from('<H', raw, e_lfanew + 6)[0]
    opt_size = struct.unpack_from('<H', raw, e_lfanew + 20)[0]
    opt = e_lfanew + 24
    assert struct.unpack_from('<H', raw, opt)[0] == 0x10b, 'PE32 expected'
    base = struct.unpack_from('<I', raw, opt + 28)[0]
    secs = []
    sh = opt + opt_size
    for i in range(nsec):
        o = sh + 40 * i
        name = raw[o:o + 8].rstrip(b'\0').decode('ascii', 'replace')
        vsize, va, rsize, rptr = struct.unpack_from('<IIII', raw, o + 8)
        secs.append((name, base + va, vsize, rsize, rptr))
    return secs


def read_inventory(path):
    rows = []
    with open(path, newline='') as fh:
        hdr = fh.readline().rstrip('\n').split('\t')
        for line in fh:
            if not line.strip():
                continue
            d = dict(zip(hdr, line.rstrip('\n').split('\t')))
            rows.append(dict(addr=int(d['addr'], 16), size=int(d['size']), glob=d['glob'], section=d['section'],
                             kind=d['kind'], rows=d.get('rows', '')))
    rows.sort(key=lambda r: r['addr'])
    return rows


def fnv1a(entries):
    h = 2166136261
    for addr, data in entries:
        for b in struct.pack('<II', addr, len(data)) + bytes(data):
            h ^= b
            h = (h * 16777619) & 0xffffffff
    return h


def resolve(raw, secs, inv):
    """Map every inventory row to its file bytes. Returns (entries, errors)."""
    errs, entries = [], []
    prev_end = 0
    for r in inv:
        a, n = r['addr'], r['size']
        if a < prev_end:
            errs.append('0x%08x %s overlaps the previous range (ends 0x%08x)' % (a, r['glob'], prev_end))
        prev_end = max(prev_end, a + n)
        hit = None
        for name, va, vs, rs, rp in secs:
            if va <= a < va + max(vs, rs):
                hit = (name, va, vs, rs, rp)
                break
        if not hit:
            errs.append('0x%08x %s maps to no section' % (a, r['glob']))
            continue
        name, va, vs, rs, rp = hit
        off = a - va
        if off + n > rs:
            errs.append('0x%08x %s (+%d) reaches past %s file data (raw 0x%x): uninitialized tail, no file bytes'
                        % (a, r['glob'], n, name, rs))
            continue
        if r['section'] and r['section'] != name:
            errs.append('0x%08x %s: inventory says %s, PE says %s' % (a, r['glob'], r['section'], name))
        data = raw[rp + off: rp + off + n]
        if r['kind'] == 'string' and data[-1:] != b'\0':
            errs.append('0x%08x %s: string entry of %d bytes does not end on its NUL' % (a, r['glob'], n))
        entries.append((a, data, r))
    return entries, errs


def c_ident_ok(s):
    return re.sub(r'[^0-9A-Za-z_]', '_', s)


def render(entries, inv_path, inv_sha, bin_sha):
    pairs = [(a, d) for a, d, _ in entries]
    h = fnv1a(pairs)
    total = sum(len(d) for _, d in pairs)
    rel_inv = os.path.relpath(inv_path, REPO).replace('\\', '/')
    out = []
    out.append('// GENERATED by re/tools/gen_portstate_seed.py. Do not edit: regenerate, then run it with --check.')
    out.append('// PORT-STATE-02, decision L-99 (a): file-backed .rdata / .data values of the original at their original')
    out.append('// addresses, for exactly the addresses of the inventory below. Consumer: Compat/PortStateSeed.cpp.')
    out.append('// inventory: %s sha256 %s' % (rel_inv, inv_sha))
    out.append('// binary:    original/MASHED.exe.unpatched sha256 %s' % bin_sha)
    out.append('// entries %d, bytes %d' % (len(pairs), total))
    out.append('// FNV-1a 32 over (addr u32 LE, len u32 LE, bytes) per entry in address order:')
    out.append('#define MASHED_PORTSTATE_SEED_ENTRIES %du' % len(pairs))
    out.append('#define MASHED_PORTSTATE_SEED_BYTES %du' % total)
    out.append('#define MASHED_PORTSTATE_SEED_FNV1A 0x%08xu' % h)
    out.append('')
    out.append('static const unsigned char kPortStateSeedData[%d] = {' % total)
    off = 0
    offs = []
    for a, d, r in entries:
        offs.append(off)
        out.append('    // 0x%08x %s (%s, %d)' % (a, c_ident_ok(r['glob']), r['section'], len(d)))
        for i in range(0, len(d), 16):
            out.append('    ' + ' '.join('0x%02x,' % b for b in d[i:i + 16]))
        off += len(d)
    out.append('};')
    out.append('')
    out.append('static const PortStateSeedEntry kPortStateSeedEntries[%d] = {' % len(pairs))
    for (a, d, r), o in zip(entries, offs):
        out.append('    { 0x%08xu, %4du, %4du },   // %s, read by %s' % (a, len(d), o, c_ident_ok(r['glob']),
                                                                     r['rows'] or '-'))
    out.append('};')
    out.append('')
    return '\n'.join(out), h


def parse_inc(text):
    """(entries [(addr, bytes)], recorded fnv) from a generated .inc."""
    m = re.search(r'#define MASHED_PORTSTATE_SEED_FNV1A 0x([0-9a-f]{8})u', text)
    rec = int(m.group(1), 16) if m else None
    dm = re.search(r'kPortStateSeedData\[\d+\] = \{(.*?)\};', text, re.S)
    data = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-f]{2}),', re.sub(r'//[^\n]*', '', dm.group(1)))) if dm else b''
    em = re.search(r'kPortStateSeedEntries\[\d+\] = \{(.*?)\};', text, re.S)
    ents = []
    if em:
        for a, n, o in re.findall(r'\{ 0x([0-9a-f]{8})u,\s*(\d+)u,\s*(\d+)u \}', em.group(1)):
            a, n, o = int(a, 16), int(n), int(o)
            ents.append((a, data[o:o + n]))
    return ents, rec


def sha256(path):
    return hashlib.sha256(open(path, 'rb').read()).hexdigest().upper()


def sha256_text(path):
    """SHA-256 of a text file with CRLF folded to LF, so the checkout's line endings do not change it."""
    return hashlib.sha256(open(path, 'rb').read().replace(b'\r\n', b'\n')).hexdigest().upper()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--inventory', default=INV_DEFAULT)
    ap.add_argument('--out', default=OUT_DEFAULT)
    ap.add_argument('--unpatched', default=None)
    a = ap.parse_args()

    tag = '[portstate-seed]'
    if not os.path.isfile(a.inventory):
        if a.check:
            print('%s SKIP: no inventory at %s' % (tag, a.inventory))
            return 0
        print('%s ERROR: no inventory at %s' % (tag, a.inventory))
        return 1
    inv = read_inventory(a.inventory)
    inv_sha = sha256_text(a.inventory)
    binp = a.unpatched or find_unpatched()

    if a.check:
        if not os.path.isfile(a.out):
            print('%s FAIL: %s missing' % (tag, a.out))
            return 1
        text = open(a.out).read()
        ents, rec = parse_inc(text)
        bad = []
        if rec is None or fnv1a(ents) != rec:
            bad.append('recorded FNV-1a %s != recomputed 0x%08x' % (('0x%08x' % rec) if rec is not None else 'none',
                                                                  fnv1a(ents)))
        want = [(r['addr'], r['size']) for r in inv]
        have = [(e[0], len(e[1])) for e in ents]
        if want != have:
            missing = sorted(set(want) - set(have))
            extra = sorted(set(have) - set(want))
            bad.append('table != inventory: %d missing %s, %d extra %s' % (
                len(missing), ' '.join('0x%08x+%d' % x for x in missing[:8]),
                len(extra), ' '.join('0x%08x+%d' % x for x in extra[:8])))
        if inv_sha not in text:
            bad.append('inventory sha256 %s not recorded in the .inc (regenerate)' % inv_sha[:16])
        if binp and os.path.isfile(binp):
            bsha = sha256(binp)
            if bsha != ANCHOR:
                bad.append('binary %s sha256 %s is not the anchor' % (binp, bsha))
            else:
                raw = open(binp, 'rb').read()
                resolved, errs = resolve(raw, pe_sections(raw), inv)
                bad += errs
                fromb = {ad: d for ad, d, _ in resolved}
                diff = [ad for ad, d in ents if fromb.get(ad) is not None and fromb[ad] != d]
                if diff:
                    bad.append('%d entries differ from the binary: %s' % (len(diff), ' '.join('0x%08x' % x for x in diff[:8])))
            binleg = 'binary checked'
        else:
            binleg = 'binary leg SKIPPED (no original/MASHED.exe.unpatched)'
        if bad:
            for b in bad:
                print('%s FAIL: %s' % (tag, b))
            return 1
        print('%s OK: %d entries, %d bytes, fnv 0x%08x, %s' % (tag, len(ents), sum(len(d) for _, d in ents), rec,
                                                              binleg))
        return 0

    if not binp or not os.path.isfile(binp):
        print('%s ERROR: original/MASHED.exe.unpatched not found (set MASHED_UNPATCHED)' % tag)
        return 1
    bsha = sha256(binp)
    if bsha != ANCHOR:
        print('%s REFUSED: %s sha256 %s is not the anchor %s' % (tag, binp, bsha, ANCHOR))
        return 1
    raw = open(binp, 'rb').read()
    entries, errs = resolve(raw, pe_sections(raw), inv)
    if errs:
        for e in errs:
            print('%s REFUSED: %s' % (tag, e))
        return 1
    text, h = render(entries, a.inventory, inv_sha, bsha)
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, 'w', newline='\n') as fh:
        fh.write(text)
    print('%s wrote %s: %d entries, %d bytes, fnv 0x%08x' % (tag, os.path.relpath(a.out, REPO), len(entries),
                                                             sum(len(d) for _, d, _ in entries), h))
    return 0


if __name__ == '__main__':
    sys.exit(main())
