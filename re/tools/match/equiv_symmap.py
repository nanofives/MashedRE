"""Build re/tools/match/equiv_symmap.tsv: the original's address of every relocation symbol that has no address in
its name (CRT helpers such as __ftol, import slots __imp__X@N, ...), read from byte-identical matches.

In a byte-identical function (match_ledger.tsv verdict PASS) our relocation site k sits at the same offset as the
original's operand, so the original operand gives S = operand - A (DIR32) or S = target - A (REL32), A being our
stored field. A name is kept only when every PASS function that uses it gives the same S.

    py -3.12 re/tools/match/equiv_symmap.py [--jobs 6]
"""
import argparse
import collections
import concurrent.futures as cf
import pathlib
import re
import struct
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import match  # noqa: E402

ROOT = HERE.parents[2]
LEDGER = ROOT / "re" / "analysis" / "match_ledger.tsv"
OUT = HERE / "equiv_symmap.tsv"
NAMED = re.compile(r"^(?:_|@)*(?:thunk_FUN|FUN|DAT|PTR|UNK|BYTE|WORD|DWORD|QWORD|FLOAT|DOUBLE|s|u|PTR_FUN|PTR_DAT)_[0-9a-fA-F]{8}")
RE_G = re.compile(r"MGLOBALA?\(\s*[^,]+?,\s*(\w+)\s*,\s*(?:[^,;\n]+,\s*)?(0x[0-9a-fA-F]+)\s*\)")


def one(src_rvas):
    src, rvas = src_rvas
    out = []
    try:
        p = ROOT / src
        text = p.read_text()
        gl = {n for n, _ in RE_G.findall(text)}
        secs, syms = match.coff(match.compile_obj(p, match.file_flags(text) or match.DEFAULT_FLAGS,
                                                  match.file_lang(text), match.file_toolchain(text)))
        by_index = {s["index"]: s for s in syms}
        for addr, sym in match.parse_annotations(text):
            if addr not in rvas:
                continue
            fns = [s for s in syms if s["sec"] > 0 and s["type"] == 0x20 and s["name"] == sym] or \
                  [s for s in syms if s["sec"] > 0 and s["type"] == 0x20 and sym in s["name"]]
            if not fns:
                continue
            s = fns[0]
            sec = secs[s["sec"] - 1]
            start = s["value"]
            later = sorted(x["value"] for x in syms if x["sec"] == s["sec"] and x["type"] == 0x20 and x["value"] > start)
            end = later[0] if later else len(sec["data"])
            orig = match.original_bytes(addr, end - start + 8)
            for off, si, typ in sec["relocs"]:
                if not (start <= off < end):
                    continue
                t = by_index.get(si, {})
                name = t.get("name", "")
                if t.get("sec", 0) != 0 or NAMED.match(name) or name.lstrip("_@").split("@")[0] in gl:
                    continue
                site = off - start
                field = struct.unpack_from("<i", sec["data"], off)[0]
                if typ == 0x06:
                    v = struct.unpack_from("<I", orig, site)[0]
                elif typ == 0x14:
                    v = (addr + site + 4 + struct.unpack_from("<i", orig, site)[0]) & 0xFFFFFFFF
                else:
                    continue
                out.append((name, (v - field) & 0xFFFFFFFF, f"0x{addr:08x}"))
    except BaseException as e:  # noqa: BLE001
        return src, [], str(e)[:100]
    return src, out, None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=6)
    a = ap.parse_args()
    rows = [ln.split("\t") for ln in LEDGER.read_text().splitlines()[1:] if ln.strip()]
    by_src = collections.defaultdict(set)
    for r in rows:
        if r[14] == "PASS" and r[1] and r[1] != "-":
            by_src[r[1]].add(int(r[0], 16))
    seen = collections.defaultdict(collections.Counter)
    where = collections.defaultdict(list)
    errs = 0
    items = sorted(by_src.items())
    with cf.ProcessPoolExecutor(a.jobs) as ex:
        for i, (src, out, err) in enumerate(ex.map(one, items)):
            if err:
                errs += 1
            for name, v, w in out:
                seen[name][v] += 1
                where[name].append(w)
            if (i + 1) % 100 == 0:
                print(f"[{i + 1}/{len(items)}] files", flush=True)
    lines = ["# name\taddress\tn_functions\t(generated by equiv_symmap.py from match_ledger PASS rows; conflicting names dropped)"]
    dropped = []
    for name in sorted(seen):
        c = seen[name]
        if len(c) == 1 and "stub" not in name.lower():
            (v, n), = c.items()
            lines.append(f"{name}\t0x{v:08x}\t{n}")
        else:
            dropped.append(f"{name}: {dict((hex(k), n) for k, n in c.items())}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(lines) - 1} names kept, {len(dropped)} dropped (conflicting), {errs} files with errors -> {OUT}")
    for d in dropped:
        print("  dropped", d)


if __name__ == "__main__":
    main()
