"""Mechanical C2 plates for MASHED.exe, generated from the anchored bytes plus the Ghidra function list.
Ported from SimGolf `re/tools/c2_note.py`; emits Mashed's plate schema (re/CONFIDENCE.md C2, the
`scribe-transcriber` shape): frontmatter, `## Mechanical description`, `## Constants`, `## Uncertainties`,
`## Stubs encountered`.

What it transcribes, each item cited by instruction address:
  - signature: callee stack cleanup (`ret N`), registers read before any write (register arguments,
    including the non-MSVC ones such as AL), incoming stack arguments read (esp depth tracked over the CFG),
    the convention those facts select, and Ghidra's stored prototype;
  - every memory read and write with its width, x87/SSE type and sign/zero extension;
  - every flag consumer (jcc/setcc/cmovcc/sbb/adc) with its signedness and the instruction that set the flags;
  - signed vs unsigned arithmetic (sar/shr, imul/mul, idiv/div, cdq, fild/fist);
  - callees with incremental/import thunks resolved, import calls, indirect calls, jump tables enumerated;
  - callers from Ghidra's references (calls and non-call references such as `push <fn>`);
  - every immediate and every absolute-address operand, with the file bytes for file-backed addresses.

It never writes a purpose, a name or a role: the plate is a transcription, and the C3 `## Purpose` is
hand-written later. It never overwrites a file that lacks the generator marker.

    py -3.12 re/tools/c2_note.py 0x004a4541                       # print one plate
    py -3.12 re/tools/c2_note.py --file rvas.txt --out-dir <dir>  # write <dir>/<rva>.md for each address
    py -3.12 re/tools/c2_note.py --c1 --out-dir re/analysis/c2gen --tsv log/c2_batch.tsv
                                                                  # every C1 row of hooks.csv; TSV for re-classify
"""
