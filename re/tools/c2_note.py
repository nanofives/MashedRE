WIDTH = {1: "byte", 2: "word", 4: "dword", 6: "fword", 8: "qword", 10: "tword", 16: "xmmword"}
REGS32 = ("eax", "ecx", "edx", "ebx", "esi", "edi")
FAMILY = {"eax": {"eax", "ax", "al", "ah"}, "ecx": {"ecx", "cx", "cl", "ch"}, "edx": {"edx", "dx", "dl", "dh"},
          "ebx": {"ebx", "bx", "bl", "bh"}, "esi": {"esi", "si"}, "edi": {"edi", "di"},
          "esp": {"esp", "sp"}, "ebp": {"ebp", "bp"}}
X87_CONST = {"fldz": "+0.0", "fld1": "+1.0", "fldpi": "pi", "fldl2e": "log2(e)", "fldl2t": "log2(10)",
             "fldlg2": "log10(2)", "fldln2": "ln(2)"}
CC = {  # condition suffix -> (kind, flags read)
    "e": ("equality", "ZF"), "ne": ("equality", "ZF"),
    "l": ("signed", "SF!=OF"), "ge": ("signed", "SF==OF"), "le": ("signed", "ZF|SF!=OF"), "g": ("signed", "!ZF&SF==OF"),
    "b": ("unsigned", "CF"), "ae": ("unsigned", "!CF"), "be": ("unsigned", "CF|ZF"), "a": ("unsigned", "!CF&!ZF"),
    "s": ("sign bit", "SF"), "ns": ("sign bit", "!SF"), "o": ("overflow", "OF"), "no": ("overflow", "!OF"),
    "p": ("parity", "PF"), "np": ("parity", "!PF"),
}
HEDGE = re.compile(r"\b(probably|likely|seems?|appears?|apparently|presumably|maybe|perhaps|possibly|might|"
                   r"guess(?:ed)?|suggests?|i think|could be|should be)\b", re.I)
_FLAGBITS = 0
for _n in dir(x86):
    if re.fullmatch(r"X86_EFLAGS_(MODIFY|RESET|SET|UNDEFINED)_(CF|ZF|SF|OF|PF)", _n):
        _FLAGBITS |= getattr(x86, _n)


def hexa(v):
    return f"0x{v:08x}"


def addr_list(addrs, limit=12):
    a = sorted(set(addrs))
    s = ", ".join(hexa(x) for x in a[:limit])
    return s + (f" (+{len(a) - limit} more)" if len(a) > limit else "")


def is_fpu(ins):
    return x86.X86_GRP_FPU in ins.groups or ins.mnemonic.startswith("f")


def sets_flags(ins):
    m = ins.mnemonic
    if m in ("fcomi", "fcomip", "fucomi", "fucomip", "sahf", "popfd", "popf"):
        return True
    if is_fpu(ins):
        return False
    try:
        return bool(ins.eflags & _FLAGBITS)
    except Exception:
        return False


def cond_of(m):
    """Condition suffix of a flag consumer, or None."""
    for pre in ("cmov", "set", "j", "fcmov"):
        if m.startswith(pre) and m != "jmp" and m not in ("jecxz", "jcxz"):
            suf = m[len(pre):]
            if pre == "fcmov":
                return {"b": "b", "e": "e", "be": "be", "u": "p", "nb": "ae", "ne": "ne", "nbe": "a", "nu": "np"}.get(suf)
            return suf if suf in CC else None
    return None


def operand_text(ins, op):
    m = op.mem
    parts = []
    if m.base:
        parts.append(ins.reg_name(m.base))
    if m.index:
        parts.append(f"{ins.reg_name(m.index)}*{m.scale}" if m.scale != 1 else ins.reg_name(m.index))
    d = m.disp
    if parts:
        s = "+".join(parts) + (f"+0x{d:x}" if d > 0 else (f"-0x{-d:x}" if d < 0 else ""))
    else:
        s = hexa(d & 0xFFFFFFFF)
    seg = ins.reg_name(m.segment) + ":" if m.segment else ""
    return f"{seg}[{s}]"


def mem_type(ins, op):
    """Width plus the data type the instruction itself fixes (x87/SSE/extension), never a guess."""
    m, sz = ins.mnemonic.split()[-1], op.size
    w = WIDTH.get(sz, f"{sz}-byte")
    if ins.mnemonic.startswith(("rep", "repe", "repne")):
        w += f" per element, `{ins.mnemonic.split()[0]}` prefix (repeated by ecx)"
    if is_fpu(ins):
        if m in ("fnstcw", "fldcw", "fstcw"):
            return f"{w} (x87 control word)"
        if m in ("fnstsw", "fstsw"):
            return f"{w} (x87 status word)"
        if m in ("fnsave", "frstor", "fnstenv", "fldenv", "fxsave", "fxrstor"):
            return f"{w} (x87 state image)"
        if m.startswith("fi") or m in ("fisttp",):
            return f"{w} (x87 signed int{8 * sz})"
        if m in ("fbld", "fbstp"):
            return f"{w} (x87 packed BCD)"
        return f"{w} (x87 float{8 * sz})"
    if re.search(r"(ss|^cvtsi2ss|^cvtss2si)$", m) or m in ("comiss", "ucomiss", "movss"):
        return f"{w} (SSE float32)"
    if re.search(r"sd$", m) and m not in ("movsd",) or m in ("comisd", "ucomisd"):
        return f"{w} (SSE float64)"
    return w


X87_STORES = {"fst", "fstp", "fist", "fistp", "fisttp", "fbstp", "fnstcw", "fstcw", "fnstsw", "fstsw",
              "fnstenv", "fstenv", "fnsave", "fsave", "fxsave"}
READ_ONLY = {"cmp", "test", "bt", "push", "call", "jmp", "cmps", "cmpsb", "cmpsw", "cmpsd", "scasb", "scasw", "scasd",
             "comiss", "comisd", "ucomiss", "ucomisd", "prefetchnta", "prefetcht0", "prefetcht1", "prefetcht2"}
BOTH = {"xchg", "xadd", "cmpxchg"}


def mem_access(ins, i):
    """(read, write) for memory operand i, from the instruction's defined semantics. Capstone 5's
    operand.access is wrong for several store forms (fstp/fst/fistp m32/fnstcw report READ, movups/movq
    stores report READ, cmpxchg reports READ only), so it is not used. Measured 2026-10-11."""
    m = ins.mnemonic.split()[-1]                       # drop rep/lock prefixes
    if is_fpu(ins):
        return m not in X87_STORES, m in X87_STORES
    if m in BOTH:
        return True, True
    if i > 0:
        return True, False
    if m in READ_ONLY or m.startswith(("cmps", "scas")):
        return True, False
    if m.startswith(("mov", "stos", "set", "cvt")) or m in ("pop", "lods", "lodsb", "lodsw", "lodsd"):
        return False, True
    return True, True


def reg_source(insns, k, reg, targets):
    """(absolute address, insn address) when the last write to `reg` before insns[k], scanning back within the
    straight-line block (stopping at a branch target or a call that clobbers it), is `mov reg, dword ptr [abs]`."""
    for j in range(k - 1, max(-1, k - 64), -1):
        q = insns[j]
        try:
            _, ww = q.regs_access()
        except capstone.CsError:
            return None
        if reg in {q.reg_name(x) for x in ww} or (q.mnemonic == "call" and reg in ("eax", "ecx", "edx")):
            o = q.operands
            if q.mnemonic == "mov" and len(o) == 2 and o[1].type == x86.X86_OP_MEM and not o[1].mem.base                     and not o[1].mem.index:
                return o[1].mem.disp & 0xFFFFFFFF, q.address
            return None
        if insns[j].address in targets and j < k:
            # a branch target: another path may reach the call with a different value; stop unless this
            # block was entered only by fall-through, which the generator does not establish
            return None
    return None


class Ctx:
    def __init__(self):
        xref.check_anchor()
        self.meta, self.fx = xref.facts()
        self.iat = xref.iat()
        self.entries = set(self.fx)
        self.hooks = {}
        for r in csv.DictReader(open(ROOT / "hooks.csv", encoding="utf-8", errors="replace", newline="")):
            if r["rva"] and not r["rva"].startswith("#"):
                try:
                    self.hooks[int(r["rva"], 16)] = r
                except ValueError:
                    pass
        self._purge = {}

    def name(self, va):
        r = self.hooks.get(va)
        g = self.fx.get(va, {}).get("name")
        if r and r["name"] and not re.match(r"(FUN|sub)_[0-9a-fA-F]{8}$", r["name"]):
            return r["name"]
        return g or (r["name"] if r else hexa(va))  # no Ghidra function and no hooks.csv row: the raw address

    def conf(self, va):
        r = self.hooks.get(va)
        return r["confidence"] if r and r["confidence"] else "absent"

    def resolve(self, t):
        """(final target, chain text). Follows Ghidra thunks and 5-byte `jmp rel32` / `jmp [IAT]` stubs."""
        chain, seen = [], set()
        while t not in seen:
            seen.add(t)
            f = self.fx.get(t)
            if f and isinstance(f["thunk"], str):
                return f["thunk"][len("EXTERNAL:"):], chain + [hexa(t)]
            if f and isinstance(f["thunk"], int):
                chain.append(hexa(t))
                t = f["thunk"]
                continue
            b = xref.read_bytes(t, 6)
            if b and b[0] == 0xE9:
                chain.append(hexa(t))
                t = (t + 5 + int.from_bytes(b[1:5], "little", signed=True)) & 0xFFFFFFFF
                continue
            if b and b[0] == 0xFF and b[1] == 0x25:
                slot = int.from_bytes(b[2:6], "little")
                if slot in self.iat:
                    return "{}!{}".format(*self.iat[slot]), chain + [hexa(t)]
            break
        return t, chain

    def purge(self, va, _depth=0):
        """Bytes the callee pops (`ret N`) when every `ret` in its body agrees; "noreturn" when the body has no
        `ret` and its last instruction is a call; a tail `jmp` out of the body defers to the jump target;
        None otherwise."""
        if va not in self._purge:
            f = self.fx.get(va)
            n = None
            if f:
                insns, _ = xref.disasm(f["ranges"])
                insns.sort(key=lambda i: i.address)
                pops = {(i.operands[0].imm if i.operands else 0) for i in insns if i.mnemonic.startswith("ret")}
                if len(pops) == 1:
                    n = pops.pop()
                elif not pops and insns:
                    last = insns[-1]
                    if last.mnemonic == "call":
                        n = "noreturn"
                    elif last.mnemonic == "jmp" and last.operands and last.operands[0].type == x86.X86_OP_IMM                             and _depth < 4:
                        t, _ = self.resolve(last.operands[0].imm & 0xFFFFFFFF)
                        n = self.purge(t, _depth + 1) if isinstance(t, int) else None
            self._purge[va] = n
        return self._purge[va]


# ---------------------------------------------------------------- esp depth over the CFG
def stack_depths(ctx, insns, ranges, entry):
    """Map ins.address -> (depth, ebp_depth) where depth = bytes pushed since entry (entry = 0, so
    [esp+K] is entry offset K - depth). None = not determined (reason recorded in `lost`)."""
    by = {i.address: k for k, i in enumerate(insns)}
    inside = lambda t: any(lo <= t < hi for lo, hi in ranges)
    state, lost, conflict, joined, noret = {}, {}, set(), set(), {}
    work = [(entry, (0, None))]
    while work:
        a, st = work.pop()
        if a not in by:
            continue
        if a in state:
            if state[a] == st:
                continue
            old = state[a]
            if old[0] is not None and st[0] is not None and old[0] != st[0]:
                conflict.add(a)
                st = (None, None)
            elif old[0] is None or st[0] is None:
                # one incoming path lost the depth: keep the determined one, and list the join
                joined.add(a)
                known = old if old[0] is not None else st
                st = (known[0], known[1] if old[1] == st[1] else (known[1] if None in (old[1], st[1]) else None))
            else:
                st = (st[0], old[1] if old[1] == st[1] else None)
            if state[a] == st:
                continue
        state[a] = st
        ins = insns[by[a]]
        d, e = st
        m, ops = ins.mnemonic, ins.operands
        nd, ne = d, e
        if d is not None:
            if m == "push":
                nd = d + (2 if ops and ops[0].size == 2 else 4)
            elif m in ("pushal", "pushad"):
                nd = d + 32
            elif m in ("pushfd", "pushf"):
                nd = d + 4
            elif m == "pop":
                nd = d - 4
                if ops and ops[0].type == x86.X86_OP_REG and ins.reg_name(ops[0].reg) == "esp":
                    nd = None
            elif m in ("popal", "popad"):
                nd = d - 32
            elif m in ("popfd", "popf"):
                nd = d - 4
            elif m == "leave":
                nd = None if e is None else e - 4
            elif m in ("sub", "add") and ops and ops[0].type == x86.X86_OP_REG and ins.reg_name(ops[0].reg) == "esp":
                nd = (d + ops[1].imm if m == "sub" else d - ops[1].imm) if ops[1].type == x86.X86_OP_IMM else None
            elif m == "mov" and ops[0].type == x86.X86_OP_REG and ops[1].type == x86.X86_OP_REG:
                dst, src = ins.reg_name(ops[0].reg), ins.reg_name(ops[1].reg)
                if dst == "ebp" and src == "esp":
                    ne = d
                elif dst == "esp" and src == "ebp":
                    nd = e
            elif m == "lea" and ops[0].type == x86.X86_OP_REG and ins.reg_name(ops[0].reg) == "esp":
                mb = ins.reg_name(ops[1].mem.base) if ops[1].mem.base else None
                if mb == "esp" and not ops[1].mem.index:
                    nd = d - ops[1].mem.disp
                elif mb == "ebp" and not ops[1].mem.index and e is not None:
                    nd = e - ops[1].mem.disp
                else:
                    nd = None
            elif m == "call":
                if ops and ops[0].type == x86.X86_OP_IMM:
                    tgt, _ = ctx.resolve(ops[0].imm & 0xFFFFFFFF)
                    p = ctx.purge(tgt) if isinstance(tgt, int) else None
                    if p == "noreturn":
                        noret[a] = tgt
                        state[a] = st
                        continue
                    if p is None:
                        nd = None
                        lost[a] = f"call {hexa(ops[0].imm & 0xFFFFFFFF)}: callee stack cleanup not fixed by a single `ret N`"
                    else:
                        nd = d - p
                else:
                    nd = None
                    lost[a] = f"`{m} {ins.op_str}`: callee stack cleanup unknown (indirect or import call)"
            else:
                try:
                    _, ww = ins.regs_access()
                    if any(ins.reg_name(r) == "esp" for r in ww) and m not in ("ret", "retn", "call", "push", "pop"):
                        nd = None
                        lost[a] = f"`{m} {ins.op_str}` writes esp"
                    if any(ins.reg_name(r) == "ebp" for r in ww):
                        ne = None
                except capstone.CsError:
                    pass
        else:
            if m == "mov" and ops and ops[0].type == x86.X86_OP_REG and ops[1].type == x86.X86_OP_REG \
                    and ins.reg_name(ops[0].reg) == "esp" and ins.reg_name(ops[1].reg) == "ebp" and e is not None:
                nd = e
        nxt = (nd, ne)
        if m.startswith("ret"):
            continue
        if m == "jmp":
            if ops and ops[0].type == x86.X86_OP_IMM and inside(ops[0].imm & 0xFFFFFFFF):
                work.append((ops[0].imm & 0xFFFFFFFF, nxt))
            continue
        if m.startswith("j") or m.startswith("loop"):
            if ops and ops[0].type == x86.X86_OP_IMM:
                work.append((ops[0].imm & 0xFFFFFFFF, nxt))
        if m == "call" and ops and ops[0].type == x86.X86_OP_IMM:
            tgt, _ = ctx.resolve(ops[0].imm & 0xFFFFFFFF)
            if isinstance(tgt, str) and tgt.split("!")[-1] in ("ExitProcess", "_exit", "exit", "abort", "RaiseException"):
                continue
        work.append((a + ins.size, nxt))
    return state, lost, conflict, joined, noret


def stack_label(ins, op, st):
    """Entry-relative label for an esp/ebp-based operand, or None."""
    if not op.mem.base or op.mem.index:
        return None
    b = ins.reg_name(op.mem.base)
    d, e = st if st else (None, None)
    if b == "esp" and d is not None:
        off = op.mem.disp - d
    elif b == "ebp" and e is not None:
        off = op.mem.disp - e
    else:
        return None
    if off >= 4:
        n, r = divmod(off - 4, 4)
        return f"arg{n}" + (f"+{r}" if r else "") + f" (entry esp+0x{off:x})"
    if off == 0:
        return "return address (entry esp+0x0)"
    return f"local entry esp-0x{-off:x}"


# ---------------------------------------------------------------- the plate
def note(ctx, va, subsystem=None, date=None, uid=None):
    f = ctx.fx.get(va)
    if f is None:
        return None
    ranges = f["ranges"]
    insns, short = xref.disasm(ranges)
    insns.sort(key=lambda i: i.address)
    by = {i.address: k for k, i in enumerate(insns)}
    size = sum(hi - lo for lo, hi in ranges)
    inside = lambda t: any(lo <= t < hi for lo, hi in ranges)
    depths, lost, conflict, joined, noret = stack_depths(ctx, insns, ranges, va)
    img_lo = xref.base()
    img_hi = img_lo + xref.load_pe().OPTIONAL_HEADER.SizeOfImage

    targets = set()
    for ins in insns:
        if (ins.mnemonic.startswith("j") or ins.mnemonic.startswith("loop")) and ins.operands \
                and ins.operands[0].type == x86.X86_OP_IMM:
            targets.add(ins.operands[0].imm & 0xFFFFFFFF)

    reads, writes, ext = collections.defaultdict(list), collections.defaultdict(list), {}
    flagc, arith = [], []
    callees, imports, indirect, tails = (collections.defaultdict(list) for _ in range(4))
    tables = {}
    consts, absmem = collections.defaultdict(list), collections.defaultdict(list)
    espadj = collections.defaultdict(list)
    leas = collections.defaultdict(list)
    implicit = collections.defaultdict(list)
    rets = []
    unreached_stack = set()

    for k, ins in enumerate(insns):
        m, ops = ins.mnemonic, ins.operands
        if m.startswith("ret"):
            rets.append((ins.address, ops[0].imm if ops else 0))
            continue
        # ---- control transfers
        if m in ("call", "jmp") and ops:
            op = ops[0]
            if op.type == x86.X86_OP_IMM:
                t = op.imm & 0xFFFFFFFF
                if m == "call":
                    callees[t].append(ins.address)
                elif not inside(t):
                    tails[t].append(ins.address)
                continue
            if op.type == x86.X86_OP_MEM and not op.mem.base and not op.mem.index:
                t = op.mem.disp & 0xFFFFFFFF
                if t in ctx.iat:
                    imports[("{}!{}".format(*ctx.iat[t]), f"`{m} dword ptr [IAT]`")].append(ins.address)
                    continue
            if op.type == x86.X86_OP_MEM and m == "jmp" and not op.mem.base and op.mem.index and op.mem.scale == 4:
                tb = op.mem.disp & 0xFFFFFFFF
                ent = []
                for j in range(512):
                    b = xref.read_bytes(tb + 4 * j, 4)
                    if b is None:
                        break
                    t = int.from_bytes(b, "little")
                    if not inside(t):
                        break
                    ent.append(t)
                tables[ins.address] = (tb, ins.reg_name(op.mem.index), ent)
                reads[(operand_text(ins, op), "dword")].append(ins.address)
                continue
            txt = operand_text(ins, op) if op.type == x86.X86_OP_MEM else ins.reg_name(op.reg)
            if op.type == x86.X86_OP_REG:
                src = reg_source(insns, k, ins.reg_name(op.reg), targets)
                if src is not None and src[0] in ctx.iat:
                    imports[("{}!{}".format(*ctx.iat[src[0]]), f"`{m} {txt}` (register loaded at {hexa(src[1])} from IAT "
                             f"slot {hexa(src[0])})")].append(ins.address)
                    continue
            indirect[(m, txt)].append(ins.address)
            if op.type == x86.X86_OP_MEM:
                reads[(txt, mem_type(ins, op))].append(ins.address)
            continue
        # ---- flag consumers
        c = cond_of(m)
        if c or m in ("sbb", "adc") or m in ("jecxz", "jcxz") or m.startswith("loop"):
            if m in ("jecxz", "jcxz") or m.startswith("loop"):
                flagc.append((ins, "ecx counter", "ecx", None, None))
            else:
                kind, fl = CC[c] if c else ("carry", "CF")
                setter, between = None, None
                for j in range(k - 1, max(-1, k - 40), -1):
                    p = insns[j]
                    if insns[j + 1].address in targets and between is None:
                        between = insns[j + 1].address
                    if sets_flags(p):
                        setter = p
                        break
                    if p.mnemonic in ("call", "jmp") or p.mnemonic.startswith("ret"):
                        break
                if m in ("sbb", "adc") and not (setter is not None and setter.mnemonic in ("cmp", "neg", "sub", "add")):
                    if not (ops[0].type == x86.X86_OP_REG and ops[1].type == x86.X86_OP_REG):
                        pass
                flagc.append((ins, kind, fl, setter, between))
        # ---- signedness of arithmetic
        if m in ("movsx", "movzx"):
            arith.append((ins, f"{'sign' if m == 'movsx' else 'zero'}-extends {8 * ops[1].size} -> {8 * ops[0].size} bits"))
        elif m in ("sar", "shr", "sal", "shl", "shrd", "shld", "rol", "ror", "rcl", "rcr"):
            arith.append((ins, {"sar": "arithmetic (signed) right shift", "shr": "logical (unsigned) right shift",
                                "shrd": "double-precision logical right shift", "shld": "double-precision left shift"}
                         .get(m, "left shift" if m in ("sal", "shl") else "rotate") + f", {8 * ops[0].size}-bit"))
