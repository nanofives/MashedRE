"""Generate MSVC __declspec(naked) verbatim transcriptions of MASHED.exe functions.

Each function's bytes (original/MASHED.exe.unpatched, version anchor in CLAUDE.md) are
disassembled with capstone and re-emitted as MSVC inline asm:
  * branch targets inside the function become labels L_<addr>;
  * `call <rva>` is remapped through CALLS (rva -> C symbol); an unmapped call is an error;
  * absolute memory operands `[0xADDR]` are emitted as `ds:[0xADDR]`, except those in CONSTS,
    which are redirected to exe-safe C symbols (the standalone's .rdata is blank-mapped and
    reads 0, memory naked-asm-rdata-reads-zero-in-exe);
  * PATCH entries replace one instruction by address (used to point the RW sqrt LUT base at
    the in-process tables).
  * "indirect_calls_ok": true lets `call <reg>` / `call dword ptr [reg + disp]` through verbatim
    (a function-pointer argument, e.g. the RW collision callback FUN_00539ec0 calls at
    0x0053a643). An indirect call through an ABSOLUTE address is still an error.
Usage: py -3.12 re/tools/gen_naked_asm.py <spec.json> <out.inc>
spec: {"funcs":[{"name","start","size"}], "calls":{"0x..":"sym"}, "consts":{"0x..":"sym"},
       "patch":{"0x..":"replacement text"}, "indirect_calls_ok": bool}
"""
import json, re, sys
import capstone, pefile

EXE = "original/MASHED.exe.unpatched"
X87_1OP = {"fadd", "fsub", "fsubr", "fmul", "fdiv", "fdivr"}
INDIRECT_OK = False


def conv_operands(mn, ops, consts, labels, calls, fstart, fend, addr):
    ops = ops.replace("xword ptr", "tbyte ptr")
    if mn.startswith("j") or mn == "call":
        m = re.fullmatch(r"0x([0-9a-f]+)", ops)
        if not m and mn == "call" and INDIRECT_OK and not re.search(r"\[0x[0-9a-f]+\]", ops):
            return ops
        if not m:
            raise SystemExit(f"{addr:#x}: indirect {mn} {ops}")
        t = int(m.group(1), 16)
        if mn == "call":
            key = f"0x{t:08x}"
            if key not in calls:
                raise SystemExit(f"{addr:#x}: unmapped call {key}")
            return calls[key]
        if not (fstart <= t < fend):
            raise SystemExit(f"{addr:#x}: jump outside function {t:#x}")
        labels.add(t)
        return f"L_{t:x}"

    def mem(m):
        a = int(m.group(1), 16)
        key = f"0x{a:08x}"
        if key in consts:
            return f"[{consts[key]}]"
        return f"ds:[0x{a:08x}]"
    ops = re.sub(r"\[0x([0-9a-f]+)\]", mem, ops)
    ops = ops.replace("st(0)", "st")
    if mn in X87_1OP and re.fullmatch(r"st\(\d\)", ops):
        ops = "st, " + ops
    if mn.endswith("p") and mn[:-1] in X87_1OP | {"fadd", "fmul"} and re.fullmatch(r"st\(\d\)", ops):
        ops = ops + ", st"
    return ops


def gen(spec):
    global INDIRECT_OK
    INDIRECT_OK = bool(spec.get("indirect_calls_ok", False))
    pe = pefile.PE(EXE)
    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    calls = {k.lower(): v for k, v in spec["calls"].items()}
    consts = {k.lower(): v for k, v in spec.get("consts", {}).items()}
    patch = {int(k, 16): v for k, v in spec.get("patch", {}).items()}
    out = ["// forward declarations (inline asm cannot call a symbol declared later)"]
    for f in spec["funcs"]:
        out.append(f'extern "C" void {f["name"]}();')
    out.append("")
    for f in spec["funcs"]:
        start = int(f["start"], 16); end = start + f["size"]
        code = pe.get_data(start - 0x400000, f["size"])
        insns = list(md.disasm(code, start))
        if not insns or insns[-1].address + insns[-1].size != end:
            raise SystemExit(f"{f['name']}: disassembly does not end at {end:#x}")
        labels = set(); body = []
        for i in insns:
            if i.address in patch:
                rep = patch[i.address]
                reps = rep if isinstance(rep, list) else [rep]   # a list = several instructions
                for k, r in enumerate(reps):
                    body.append((i.address if k == 0 else None, r,
                                 f"// PATCH (was {i.mnemonic} {i.op_str})" if k == 0 else "// PATCH (cont.)"))
                continue
            if re.search(r"(movs|stos|lods|scas|cmps)[bwd]$", i.mnemonic):
                body.append((i.address, i.mnemonic, ""))     # MSVC: implicit operands only
                continue
            ops = conv_operands(i.mnemonic, i.op_str, consts, labels, calls, start, end, i.address)
            body.append((i.address, f"{i.mnemonic} {ops}".strip(), ""))
        out.append(f"// 0x{start:08x}  {f['name']}  ({f['size']} bytes, verbatim; generated by re/tools/gen_naked_asm.py)")
        out.append(f'extern "C" __declspec(naked) void {f["name"]}() {{')
        out.append("    __asm {")
        for a, t, c in body:
            if a is not None and a in labels:
                out.append(f"    L_{a:x}:")
            tag = f"{a:08x}" if a is not None else "        "
            out.append(f"        {t:<48} // {tag} {c}".rstrip())
        out.append("    }")
        out.append("}")
        out.append("")
    return "\n".join(out)


if __name__ == "__main__":
    spec = json.load(open(sys.argv[1]))
    open(sys.argv[2], "w", newline="\n").write(gen(spec))
    print("wrote", sys.argv[2])
