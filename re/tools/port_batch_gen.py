"""Write the exe-side swap of one closed set (PORT-BATCH-TOOL, D4): wrappers, build lists, wiring, manifest.

  py -3.12 re/tools/port_batch_gen.py --sub hud [--tag HUD] [--build-dir <dir>] [--dry-run]

Takes the lint- and seed-clean, default-path-reached swap set of <sub> from re/tools/port_closed_sets.py (the union of
the closures of its clean reached heads) and, per matched file of the set:
  * writes mashedmod/src/mashed_re/Match/PortBatch_<TAG>_<first rva>.cpp (exe only, MASHED_STANDALONE): MATCH_PORT,
    `#define FUN_<rva> PortBatch_<rva>` for every body of the file, `#define FUN_<callee> <exe name>` for every bound
    callee (the name port_closed_sets resolved), in-set callees -> PortBatch_<callee>, then `extern "C" { #include }`;
  * adds the TU to mashedmod/exe_sources.rsp and mashedmod/x87_tus.txt (matched code is x87 code), idempotent.
Wiring: each head is a `rebind` root, i.e. an exe-compiled matched body that the exe reaches calls FUN_<head> through
a forwarder. The shape `extern "C" void <Fwd>(void) {}` (a no-op forwarder) is rewritten in place to
`{ PortBatch_Run("<TAG>", 0x<head>u, &PortBatch_<head>); }` (the address
is a relocation, so scripts/backfill_port.py sees the edge). Any other shape is listed as MANUAL and the run
exits 2 without writing, so nothing half-wires.
Manifest: verify/portbatch_20261109/batch_<TAG>.tsv (head, rows of its closure, file, wiring site).
The switch itself is Match/PortBatch_Switch.cpp (MASHED_BATCH_<TAG>, MASHED_BATCH_<TAG>_ROWS).
"""
from __future__ import annotations

import collections
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import port_closed_sets as P      # noqa: E402

ROOT = P.ROOT
SRC = ROOT / "mashedmod" / "src" / "mashed_re"
RSP = ROOT / "mashedmod" / "exe_sources.rsp"
X87 = ROOT / "mashedmod" / "x87_tus.txt"
NL = "\n"
CRLF = "\r\n"


def rd(p):
    """Text with LF line ends (the tree is CRLF; wr() writes CRLF back)."""
    return p.read_text(encoding="utf-8", errors="replace").replace(CRLF, NL)


def wr(p, t):
    p.write_text(t.replace(CRLF, NL).replace(NL, CRLF), encoding="utf-8", newline="")


def main(argv):
    sub = argv[argv.index("--sub") + 1]
    tag = argv[argv.index("--tag") + 1] if "--tag" in argv else re.sub(r"[^A-Z0-9]", "", sub.upper())
    build = ROOT / "mashedmod" / "build"
    if "--build-dir" in argv:
        build = pathlib.Path(argv[argv.index("--build-dir") + 1]).resolve()
    dry = "--dry-run" in argv
    A = P.analyse(build)
    rv, heads = P.subsystem_sets(A, sub, True)
    if not rv:
        print("no clean reached set for", sub)
        return 1
    mf = A["mfact"]
    files = collections.OrderedDict()
    for a in sorted(rv):
        files.setdefault(mf[a]["file"], []).append(a)
    # every body of a file is compiled with it: those must all be in the set
    for f, rvas in files.items():
        allb = sorted(A["units"][f])
        if set(allb) - rv:
            print("FATAL: %s holds bodies outside the set: %s" % (f, allb))
            return 1
    cls = A["callee_cls"]

    writes, wiring, manual = {}, [], []
    for f, rvas in files.items():
        first = min(A["units"][f])
        tu = "Match/PortBatch_%s_%08x.cpp" % (tag, first)
        txt = rd(ROOT / f)
        callees = sorted({int(x, 16) for x in P.FUNREF.findall(txt)} - set(A["units"][f]))
        lines = ["// PORT-BATCH-TOOL (D4): exe-only port body of the closed set %s, generated by re/tools/port_batch_gen.py." % tag,
                 "// Matched source %s (C4 by byte match). Bodies: %s." % (f, " ".join("0x%08x" % a for a in sorted(A["units"][f]))),
                 "// Entered only when Match/PortBatch_Switch.cpp says MASHED_BATCH_%s is on (default OFF). Callees bind by name;" % tag,
                 "// no raw-address call. Do not edit by hand: regenerate.",
                 "#ifdef MASHED_STANDALONE", "#define MATCH_PORT 1"]
        for a in sorted(A["units"][f]):
            lines.append("#define FUN_%08x PortBatch_%08x" % (a, a))
        for c in callees:
            k, nm = cls.get(c, ("?", ""))
            if c in rv:
                lines.append("#define FUN_%08x PortBatch_%08x   // in the set" % (c, c))
            elif k in ("bound", "rw") and nm and nm != "thunk":
                lines.append("#define FUN_%08x %s   // %s" % (c, nm, k))
            elif nm == "thunk":
                lines.append("// FUN_%08x: one of the 6 exe RVA thunks, called by address" % c)
            else:
                print("FATAL: callee 0x%08x of %s is %s" % (c, f, k))
                return 1
        rel_inc = "../../../../" + f
        lines += ['extern "C" {', '#include "%s"' % rel_inc, "}", "#endif  // MASHED_STANDALONE", ""]
        writes[SRC / tu] = NL.join(lines)
    # wiring
    for h in heads:
        site = mf[h]["rebind"].split()
        if not site:
            manual.append((h, "no rebind site"))
            continue
        tu_rel, _rest = site[0].split(":", 1)
        fwd = _rest.split("->", 1)[1]
        p = SRC / tu_rel
        t = writes.get(p) or rd(p)
        pat = re.compile(r'(extern "C" void %s\(void\) )\{\}' % re.escape(fwd))
        if not pat.search(t):
            if ('PortBatch_Run("%s", 0x%08xu' % (tag, h)) in t:
                wiring.append((h, tu_rel, fwd, "already"))
                continue
            manual.append((h, "%s: forwarder %s is not `extern \"C\" void %s(void) {}`" % (tu_rel, fwd, fwd)))
            continue
        t2 = pat.sub(lambda m: m.group(1) + '{ PortBatch_Run("%s", 0x%08xu, &PortBatch_%08x); }' % (tag, h, h), t, count=1)
        need = ['extern "C" void __cdecl PortBatch_Run(const char* sub, unsigned rva, void (__cdecl* fn)(void));   // Match/PortBatch_Switch.cpp',
                'extern "C" void PortBatch_%08x(void);   // PORT-BATCH-TOOL %s set' % (h, tag)]
        anchor = "#ifdef MASHED_STANDALONE\n"
        ins = "".join(x + NL for x in need if x.split("(")[0] not in t2)
        if ins and anchor in t2:
            t2 = t2.replace(anchor, anchor + ins, 1)
        writes[p] = t2
        wiring.append((h, tu_rel, fwd, "rewired"))
    if manual:
        for h, why in manual:
            print("MANUAL 0x%08x %s" % (h, why))
        return 2
    # build lists
    rsp = rd(RSP)
    x87 = rd(X87)
    add_rsp, add_x87 = [], []
    for p in list(writes) + [SRC / "Match" / "PortBatch_Switch.cpp"]:
        rel = p.relative_to(SRC).as_posix()
        if not rel.startswith("Match/PortBatch_"):
            continue
        line = '"%s"' % rel.replace("/", "\\")
        if line not in rsp:
            add_rsp.append(line)
        stem = p.stem
        if not stem.endswith("Switch") and not re.search(r"^%s$" % re.escape(stem), x87, re.M):
            add_x87.append(stem)
    man = ROOT / "verify" / "portbatch_20261109" / ("batch_%s.tsv" % tag)
    rows = ["head\trows\tfile\twiring_tu\tforwarder\tstate"]
    for h, tu_rel, fwd, st in wiring:
        cl = sorted(A["closure"]([h]))
        rows.append("0x%08x\t%s\t%s\t%s\t%s\t%s" % (h, " ".join("0x%08x" % a for a in cl), mf[h]["file"], tu_rel, fwd, st))
    print(NL.join(rows))
    if dry:
        for p in writes:
            print("would write", p.relative_to(ROOT).as_posix())
        print("would add to exe_sources.rsp:", add_rsp, " x87_tus.txt:", add_x87)
        return 0
    for p, t in writes.items():
        wr(p, t)
    if add_rsp:
        wr(RSP, rsp.rstrip(NL) + NL + NL.join(add_rsp) + NL)
    if add_x87:
        wr(X87, x87.rstrip(NL) + NL + "# PORT-BATCH-TOOL %s set (re/tools/port_batch_gen.py)" % tag + NL +
           NL.join(add_x87) + NL)
    man.parent.mkdir(parents=True, exist_ok=True)
    man.write_text(NL.join(rows) + NL, encoding="utf-8", newline="")
    print("wrote %d TUs, rsp +%d, x87 +%d, manifest %s" % (len([p for p in writes if 'PortBatch_' in p.name]), len(add_rsp),
                                                         len(add_x87), man.relative_to(ROOT).as_posix()))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
