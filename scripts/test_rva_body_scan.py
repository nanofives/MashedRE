"""Self-test for `scripts/rva_body_scan.py`'s anchoring.

Why this exists: on 2026-09-29 `0x0046b1c0` shipped TWO bodies in
`mashed_re.exe` and `scripts/lint_rva_bodies.py` reported `NEW=0`
(`re/analysis/D2_REOPEN_2026-09-29.md` §15.4, commit 7908af78). The scanner
anchored the naked copy (`Vehicle/VehicleSlotAabbExpand.cpp:34`) and MISSED the
other one, because `Vehicle/VehicleInit.cpp` annotated it in a HEADER block far
above the definition instead of directly above it. One miss is enough: the
DUP-IN-TARGET check needs both.

`rva_body_scan.scan_tu` now runs a second anchoring pass for exactly that shape.
This file is the falsifiable proof, run as:

    py -3.12 scripts/test_rva_body_scan.py

It builds a synthetic TU tree, so it cannot rot with the real sources, and it
includes the negative controls that keep the second pass from inventing bodies.
"""
from __future__ import annotations

import pathlib
import sys
import tempfile

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import rva_body_scan as S            # noqa: E402

FAILED: list[str] = []


def check(name: str, got, want) -> None:
    if got == want:
        print(f"  PASS  {name}")
    else:
        print(f"  FAIL  {name}\n          got  {got}\n          want {want}")
        FAILED.append(name)


# --- the shape the guard used to miss -------------------------------------
# An RVA header comment, then a NON-signature line (the exact thing that stopped
# the first pass in VehicleInit.cpp: a `static const float ...[6] = {`), then the
# definition much further down.
UNANCHORED = """\
// Mashed RE - some subsystem.
//
// 0x0046b1c0 - VehicleBuildContactHull(slot, box)
//   builds the 14 contact-hull points from a 6-float box.
//   [0x0040ed62] call 0x0046b1c0
static const float kContactHullBox[6] = {
    0.2188f, 0.3086f, 0.4538f, -0.2188f, 0.0374f, -0.5233f,
};

void VehicleBuildContactHull(int slot, const float* b) {
    (void)slot; (void)b;
}
"""

# The classic shape the first pass has always caught.
ANCHORED = """\
// 0x0046b1c0  VehicleSlotAabbExpand
int VehicleSlotAabbExpand(unsigned slot, float* in6) {
    (void)slot; (void)in6;
    return 0;
}
"""

# NEGATIVE CONTROL 1: an RVA mentioned in call prose, with the TU's function
# defined under a DIFFERENT name and out of the first pass's reach (the next
# non-comment line is not a signature). The second pass must anchor nothing:
# the token after the RVA is `call`, which this TU does not define.
#
# STATED LIMIT, not fixed here: if the definition DID follow the comment block
# directly, the FIRST pass would bind it -- that looseness predates this file
# and is the documented "closest comment wins" rule in rva_body_scan.py. It is
# not what U-9156 set out to change.
NEG_CALLSITE = """\
// 0x00470afe  call 0x0046ef70   THIS FUNCTION
// The chain is 0x00470ae8 -> 0x00470aef -> 0x00470afe.
static int kPad1[2] = { 0, 0 };

void SomethingElse(int* self) { (void)self; }
"""

# NEGATIVE CONTROL 2: one name annotated with TWO different RVAs. Ambiguous, so
# the second pass must refuse rather than pick.
NEG_AMBIGUOUS = """\
// 0x00468d80 - AmbiguousName
// 0x004694e0 - AmbiguousName
static int kPad[2] = { 0, 0 };

void AmbiguousName(void) { }
"""

# NEGATIVE CONTROL 3: a data-range RVA (>= TEXT_END = 0x005d0000) must stay
# excluded. 0x005d8b41 is the RenderWare "Core built at" string in the anchored
# image, i.e. .rdata, not code.
NEG_DATA = """\
// 0x005d8b41 - DataOnlyThing
static int kPad3[2] = { 0, 0 };

void DataOnlyThing(void) { }
"""

# NEGATIVE CONTROL 4 (dcmix 2026-10-22): an extern DECLARATION under an RVA comment,
# with a brace a few lines below and a `)` in its trailing comment. The first pass
# used to bind it as a body (RwpSolverCore23.cpp, 0x0055e200).
NEG_DECL = """// 0x0055e200 solver-context set
extern "C" void __cdecl CtxSet(unsigned *ctx, unsigned value);   // 0x0055e200 (DONE)
static int kPad4[2] = { 0, 0 };
"""

# A one-line body whose statements end in `);` still anchors.
ONELINER = """// 0x0055e200
extern "C" void __cdecl CtxSetOne(unsigned *ctx, unsigned v) { Store(ctx, v); }
"""


# HB-LINT-408A50: an include the scanner cannot follow must be RECORDED, never skipped in
# silence (a git archive without re/match/ hid MatchS01.cpp's body of 0x00408a50).
MISSING_INC = """#include "../../../../re/match/s99/00000000.c"
#include "Nowhere_naked.inc"
"""


# FIFTH PASS (L-178, BIND-CUNCLEAN-AS-C 2026-11-21): the RW core's generated hand bodies carry their rva only in a
# `// HAND-LIFT 0x<rva> <symbol>` line (RwCore/RwCore_Lifted_NN.cpp, lifted naked asm) or a `// HAND 0x<rva> <symbol>`
# line (RwCore/RwCore_Hand.cpp). Both must anchor at that line, so a matched unit of the same rva is a visible dual body.
HAND_LIFT = """// generated by gen_rwcore_tus.py
extern "C" {
// HAND-LIFT 0x004d8090 RwCore_004d8090
__declspec(naked) void RwCore_004d8090(void) { __asm { ret } }
// HAND-LIFT 0x004dcf90 RwCore_004dcf90
__declspec(naked) void RwCore_004dcf90(void) { __asm { ret } }
}
"""

HAND = """// generated by gen_rwcore_tus.py
// HAND 0x00532b80 RwCore_00532b80
__declspec(naked) void RwCore_00532b80(void) { __asm { ret } }
"""

# NEGATIVE CONTROL 5: lookalikes the fifth pass must not read as bodies: a longer word (HANDLE), a data-range rva,
# and the marker after code on the same line (only a line that starts with the comment is a binding line).
NEG_HAND = """// HANDLE 0x00532b80 NotABody
// HAND-LIFT 0x005d8b41 DataRange
static int kPad5 = 0; // HAND 0x0053d2b0 TrailingComment
"""

# Precedence: when the first pass already anchored a body of the rva in the TU, a HAND line of the same rva does
# not replace it (setdefault: the earlier, signature-anchored body wins).
HAND_AFTER_BODY = """// 0x00557a60  RealBody
int RealBody(int a) { return a; }
// HAND 0x00557a60 RwCore_00557a60
"""


def main() -> int:
    with tempfile.TemporaryDirectory() as td:
        root = pathlib.Path(td)
        (root / "Vehicle").mkdir()
        (root / "Vehicle" / "Unanchored.cpp").write_text(UNANCHORED, encoding="utf-8")
        (root / "Vehicle" / "Anchored.cpp").write_text(ANCHORED, encoding="utf-8")
        (root / "Vehicle" / "NegCallsite.cpp").write_text(NEG_CALLSITE, encoding="utf-8")
        (root / "Vehicle" / "NegAmbiguous.cpp").write_text(NEG_AMBIGUOUS, encoding="utf-8")
        (root / "Vehicle" / "NegData.cpp").write_text(NEG_DATA, encoding="utf-8")
        (root / "Vehicle" / "NegDecl.cpp").write_text(NEG_DECL, encoding="utf-8")
        (root / "Vehicle" / "OneLiner.cpp").write_text(ONELINER, encoding="utf-8")
        (root / "Vehicle" / "MissingInc.cpp").write_text(MISSING_INC, encoding="utf-8")
        (root / "RwCore").mkdir()
        (root / "RwCore" / "Lifted.cpp").write_text(HAND_LIFT, encoding="utf-8")
        (root / "RwCore" / "Hand.cpp").write_text(HAND, encoding="utf-8")
        (root / "RwCore" / "NegHand.cpp").write_text(NEG_HAND, encoding="utf-8")
        (root / "RwCore" / "HandAfterBody.cpp").write_text(HAND_AFTER_BODY, encoding="utf-8")

        old_src = S.SRC
        S.SRC = root
        try:
            un = S.scan_tu("Vehicle/Unanchored.cpp")[0]
            an = S.scan_tu("Vehicle/Anchored.cpp")[0]
            nc = S.scan_tu("Vehicle/NegCallsite.cpp")[0]
            na = S.scan_tu("Vehicle/NegAmbiguous.cpp")[0]
            nd = S.scan_tu("Vehicle/NegData.cpp")[0]
            ne = S.scan_tu("Vehicle/NegDecl.cpp")[0]
            ol = S.scan_tu("Vehicle/OneLiner.cpp")[0]
            S.MISSING_INCLUDES.clear()
            S.scan_tu("Vehicle/MissingInc.cpp")
            mi = sorted(S.MISSING_INCLUDES)
            S.MISSING_INCLUDES.clear()
            hl = S.scan_tu("RwCore/Lifted.cpp")[0]
            hd = S.scan_tu("RwCore/Hand.cpp")[0]
            nh = S.scan_tu("RwCore/NegHand.cpp")[0]
            hb = S.scan_tu("RwCore/HandAfterBody.cpp")[0]
        finally:
            S.SRC = old_src

    print("rva_body_scan anchoring self-test")
    check("the MISSED shape is anchored (header comment far above the definition)",
          {hex(k): v[0] for k, v in un.items()},
          {"0x46b1c0": "VehicleBuildContactHull"})
    check("an unresolved re/match/ or .inc include is recorded, not skipped",
          mi,
          [("Vehicle/MissingInc.cpp", 1, "../../../../re/match/s99/00000000.c"),
           ("Vehicle/MissingInc.cpp", 2, "Nowhere_naked.inc")])
    check("the classic shape still anchors",
          {hex(k): v[0] for k, v in an.items()},
          {"0x46b1c0": "VehicleSlotAabbExpand"})
    check("BOTH bodies are seen, so the duplicate is detectable",
          sorted(set(un) & set(an)), [0x0046b1c0])
    check("NEG 1: an RVA in call prose anchors nothing", nc, {})
    check("NEG 2: one name, two RVAs -> refuse", na, {})
    check("NEG 3: a data-range RVA stays excluded", nd, {})
    check("NEG 4: a declaration is not a body", ne, {})
    check("a one-line body ending in `);` still anchors",
          {hex(k): v[0] for k, v in ol.items()}, {"0x55e200": "CtxSetOne"})
    check("HAND-LIFT lines anchor at their own line (rva, symbol, line)",
          {hex(k): v for k, v in hl.items()},
          {"0x4d8090": ("RwCore_004d8090", 3), "0x4dcf90": ("RwCore_004dcf90", 5)})
    check("a HAND line anchors at its own line (rva, symbol, line)",
          {hex(k): v for k, v in hd.items()}, {"0x532b80": ("RwCore_00532b80", 2)})
    check("NEG 5: HANDLE / data-range rva / marker after code anchor nothing", nh, {})
    check("a HAND line does not replace a first-pass body of the same rva",
          {hex(k): v[0] for k, v in hb.items()}, {"0x557a60": "RealBody"})

    print()
    if FAILED:
        print(f"FAILED: {len(FAILED)} check(s): {', '.join(FAILED)}")
        return 1
    print("OK -- 13/13")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
