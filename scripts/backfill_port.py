"""Fill the `port` column of hooks.csv (L-93, step C4R-PORTCOL, 2026-11-07).

`port` answers one question per RVA: **what does mashed_re.exe do with it?**

  none    the exe has no body for the RVA (`exe_file` is empty).
  body    the exe compiles a body for it, but no path from WinMain reaches that body.
  called  the exe's body is reachable from `WinMain` in the linked mashed_re.exe.

The column is DERIVED data. It is regenerated by this script from the current tree and the
current build, never hand-edited. Since L-93 it does not gate any confidence level: C4 certifies
the reverse engineering, `port` records the port.

How `called` is decided (the MATCH slices' exe-caller check, made whole-program):

  1  Symbols. The linker map (`mashedmod/build/mashed_re.map`, publics + static symbols) gives
     every function and data symbol, its address and its object file.
  2  RVA -> symbol. `scripts/rva_body_scan.py` gives, per exe TU, the function NAME that carries
     each RVA's body (the same scan `exe_file` comes from; MATCH includes and `.inc` files are
     anchored at the including TU). Channel B of `backfill_exe_file.py` (the dual-copy audit's
     `exe_side_copy` file:line) supplies the name of the definition at that line. The name is
     re-read from the definition's own signature, and a MATCH wrapper's `#define FUN_x Name` is
     followed. A body resolves to the map symbols whose object is `<TU stem>.obj` and whose
     undecorated base name is that name (all overloads count), else to the one .text symbol in
     the whole map with that base name when exactly one exists. A body with no symbol at all was
     inlined or never emitted: the build has no /GL, so its callers are in its own TU, and it is
     `called` when the definition enclosing one of its call lines is reachable (how=inlined).
  3  Edges. (a) every `E8`/`E9` rel32 in `.text` that lands exactly on a function start (the
     edge `verify/matchs*/tools/exe_reach.py` uses), and (b) every base relocation: a dword the
     loader relocates is an absolute address, so the symbol holding it references the symbol it
     points into. (b) is what the direct graph cannot see: `lpfnWndProc = WndProc`, vtables
     (`??_7...`, referenced by the constructor that stores them), callback tables.
  4  Walk. Breadth-first from `_WinMain@16`. Only WinMain is a root: the CRT's static
     initialisers are not (that is where the exe's no-op `RH_ScopedInstall` registrations live,
     `Stubs/HookSystemNoOp.cpp`, and they take the address of every hooked body).
  5  L-89 barrier. A symbol whose base name contains `Replay`, `SelfTest`, `Selftest` or
     `Harness` is an env-gated measurement harness: the walk reaches it but does not continue
     through it, so a body only a replay or self-test runs stays `body` (L-89: "a body only a
     test/replay harness runs is not one the game runs"). `GAME_REPLAY` lists the game's own
     replay feature, which is not a harness and is walked normally.
     L-84: a dev-only path the shipping exe carries (Nav_DevGoto) is walked like any other.

Limits, stated so the column is not over-read:
  * Static reachability, not execution. A body behind a default-OFF behaviour knob counts as
    `called` (the code path exists in the shipping exe, like L-84's dev path). A harness that is
    written inline in a game function (an `if (getenv(...))` block, not its own function) is not
    seen by the name barrier.
  * A body with no map symbol and no reachable enclosing caller stays `body` and is listed by
    `--report` with how=`unresolved` (unreferenced, or its name could not be read: a channel-B
    audit line that has drifted since 2026-09-29).
  * The answer is only as fresh as the build: the script refuses a map older than the newest
    file under `mashedmod/src` unless `--allow-stale`. It also refuses when `exe_file` is stale
    (what `backfill_exe_file.py` would write differs), so `none` is always exactly "exe_file
    empty": run `backfill_exe_file.py` first.

Rows whose width is one short of the header (a row another branch added before this column
existed) get the column appended. Any other width is left byte for byte and reported.

  py -3.12 scripts/backfill_port.py [--check] [--report <tsv>] [--build-dir <dir>] [--allow-stale]
  py -3.12 scripts/backfill_port.py --strip        # remove the column (merge-conflict recipe)

Merge-conflict recipe (hooks.csv conflicts with a branch that predates the column): run
`--strip` on both sides' copies (or resolve the 10-column versions), merge as before, then run
this script once to re-derive the column.
"""
