# ----------------------------------------------------------------------------- map + image
RE_MAP = re.compile(r"^\s*([0-9a-fA-F]{4}):([0-9a-fA-F]{8})\s+(\S+)\s+([0-9a-fA-F]{8})\s+(.*)$")


def base_name(sym: str) -> str:
    """Undecorated base name of an MSVC symbol: `?Foo@Ns@@...` -> Foo, `_Foo@12` -> Foo,
    `??$Foo@...` -> Foo, `@Foo@8` -> Foo. Constructors/operators (`??0`, `??_7`...) -> ''."""
    if sym.startswith("??$"):
        return sym[3:].split("@", 1)[0]
    if sym.startswith("??"):
        return ""
    if sym.startswith("?"):
        return sym[1:].split("@", 1)[0]
    s = sym
    if s[:1] in ("_", "@"):
        s = s[1:]
    return s.split("@", 1)[0]


def load_map(path: pathlib.Path):
    """[(va, sym, sect, obj)] for every public and static symbol with a real address."""
    out = []
    for ln in path.open(encoding="utf-8", errors="replace"):
        m = RE_MAP.match(ln)
        if not m:
            continue
        sect = int(m.group(1), 16)
        va = int(m.group(4), 16)
        if sect == 0 or va == 0:
            continue
        rest = m.group(5).split()
        obj = rest[-1] if rest else ""
        obj = obj.split(":")[-1]             # `libucrt:foo.obj` -> foo.obj
        out.append((va, m.group(3), sect, obj))
    return out


def load_image(path: pathlib.Path):
    d = path.read_bytes()
    pe = struct.unpack_from("<I", d, 0x3c)[0]
    nsec = struct.unpack_from("<H", d, pe + 6)[0]
    opt = struct.unpack_from("<H", d, pe + 20)[0]
    ib = struct.unpack_from("<I", d, pe + 24 + 28)[0]
    rel_va, rel_sz = struct.unpack_from("<II", d, pe + 24 + 96 + 8 * 5)
    secs = []
    for i in range(nsec):
        nm, vs, va, rs, ro = struct.unpack_from("<8sIIII", d, pe + 24 + opt + 40 * i)[:5]
        secs.append((nm.rstrip(b"\0").decode("ascii", "replace"), va, vs, ro, rs))
    return d, ib, secs, rel_va, rel_sz


def rva_to_off(secs, rva):
    for _nm, va, vs, ro, rs in secs:
        if va <= rva < va + max(vs, rs):
            off = rva - va
            return ro + off if off < rs else None
    return None


def build_graph(exe: pathlib.Path, mp: pathlib.Path):
    ents = load_map(mp)
    d, ib, secs, rel_va, rel_sz = load_image(exe)
    text = next(s for s in secs if s[0] == ".text")
    t_lo, t_hi = ib + text[1], ib + text[1] + text[2]

    starts = sorted({va for va, *_ in ents})
    func_starts = {va for va, _s, sect, _o in ents if t_lo <= va < t_hi}
    names_at: dict[int, list[str]] = {}
    for va, s, _sect, _o in ents:
        names_at.setdefault(va, []).append(s)

    def owner(a):
        j = bisect.bisect_right(starts, a) - 1
        return starts[j] if j >= 0 else None

    edges: dict[int, set[int]] = {}
    # (a) direct rel32 call/jmp onto a function start
    tbuf = d[text[3]:text[3] + text[4]]
    base = ib + text[1]
    for i in range(len(tbuf) - 5):
        if tbuf[i] in (0xE8, 0xE9):
            src = base + i
            t = (src + 5 + struct.unpack_from("<i", tbuf, i + 1)[0]) & 0xffffffff
            if t in func_starts:
                o = owner(src)
                if o is not None and o != t:
                    edges.setdefault(o, set()).add(t)
    # (b) base relocations: an absolute address held at p references the symbol holding its target
    nrel = 0
    off = rva_to_off(secs, rel_va)
    end = off + rel_sz
    while off is not None and off + 8 <= end:
        page, size = struct.unpack_from("<II", d, off)
        if size < 8:
            break
        for k in range((size - 8) // 2):
            e = struct.unpack_from("<H", d, off + 8 + 2 * k)[0]
            if e >> 12 != 3:                 # IMAGE_REL_BASED_HIGHLOW only
                continue
            p_rva = page + (e & 0xfff)
            po = rva_to_off(secs, p_rva)
            if po is None:
                continue
            v = struct.unpack_from("<I", d, po)[0]
            src, dst = owner(ib + p_rva), owner(v)
            if src is None or dst is None or src == dst:
                continue
            edges.setdefault(src, set()).add(dst)
            nrel += 1
        off += size
    return ents, names_at, edges, nrel, (t_lo, t_hi)


def walk(ents, names_at, edges):
    """BFS from WinMain; harness symbols are reached but not expanded. -> {va: pred}"""
    def is_barrier(va):
        for s in names_at.get(va, ()):
            b = base_name(s)
            if b and HARNESS.search(b) and b not in GAME_REPLAY:
                return True
        return False

    roots = [va for va, s, *_ in ents if s == ROOT_SYM]
    if not roots:
        raise SystemExit(f"FATAL: {ROOT_SYM} not in the map")
    prev = {roots[0]: None}
    barriers_hit = set()
    q = deque(roots[:1])
    while q:
        a = q.popleft()
        if a != roots[0] and is_barrier(a):
            barriers_hit.add(a)
            continue
        for t in edges.get(a, ()):
            if t not in prev:
                prev[t] = a
                q.append(t)
    return prev, barriers_hit


# ----------------------------------------------------------------------------- RVA -> exe bodies
RE_DEFINE = re.compile(r"^\s*#\s*define\s+([A-Za-z_]\w*)\s+([A-Za-z_][\w:]*)\s*$")


def tu_renames(rel: str) -> dict[str, str]:
    """`#define FUN_00451690 WarzonePontoonLoopCb` lines of a TU: the MATCH wrappers compile the
    byte-matched source under the port's name, so the map carries the right-hand name."""
    p = S.SRC / rel
    if not p.is_file():
        return {}
    out = {}
    for ln in p.read_text(encoding="utf-8", errors="replace").splitlines():
        m = RE_DEFINE.match(ln)
        if m:
            out[m.group(1)] = m.group(2).split("::")[-1]
    return out


_LINES: dict[str, list[str]] = {}


def tu_lines(rel: str) -> list[str]:
    """The TU's lines followed by the lines of every matched source (`re/match/*.c`) and local
    `.inc` it includes (one level): their definitions compile into the TU's own object."""
    if rel not in _LINES:
        p = S.SRC / rel
        lines = p.read_text(encoding="utf-8", errors="replace").splitlines() if p.is_file() else []
        extra = []
        for ln in lines:
            mi = S.RE_MATCH_INCLUDE.match(ln) or S.RE_INC_INCLUDE.match(ln)
            if mi:
                q = (p.parent / mi.group(1)).resolve()
                if q.is_file():
                    extra += q.read_text(encoding="utf-8", errors="replace").splitlines()
        _LINES[rel] = lines + extra
    return _LINES[rel]


def match_name(rel: str, inc: str, rva: int) -> str | None:
    """Name of the function a matched source (`#include`d by `rel`) defines for `rva`: its
    `// MATCH: 0x<rva> <sym>` line, else a definition named FUN_<rva>."""
    q = (S.SRC / rel).parent / inc
    if not q.is_file():
        return None
    lines = q.read_text(encoding="utf-8", errors="replace").splitlines()
    for ln in lines:
        m = S.RE_MATCH_LINE.match(ln)
        if m and int(m.group(1), 16) == rva:
            return m.group(2)
    want = f"FUN_{rva:08x}"
    return want if want in S._function_defs(lines) else None


RE_SIG = re.compile(r"([A-Za-z_~][\w:]*)\s*\(")
SIG_SKIP = {"__declspec", "__cdecl", "__stdcall", "__fastcall", "__thiscall", "extern", "static", "inline",
            "__forceinline", "naked", "dllexport", "noinline", "if", "while", "for", "switch", "return"}


def sig_name(lines: list[str], ln: int) -> str | None:
    """Function name of the definition that starts at 1-based line `ln`: the identifier right before
    the signature's first `(`, return type and calling convention possibly on earlier tokens or lines
    (`extern "C" __declspec(dllexport) std::uint32_t __cdecl` / `RwsFoo(...)`). None for a line that
    is an `#include` (MATCH / .inc bodies are anchored there; the scanner's name stands)."""
    if not (1 <= ln <= len(lines)) or lines[ln - 1].lstrip().startswith("#"):
        return None
    blob = " ".join(l.split("//")[0] for l in lines[ln - 1:ln + 5])
    blob = re.sub(r"__declspec\s*\([^)]*\)", " ", blob.split("{")[0])
    for m in RE_SIG.finditer(blob):
        nm = m.group(1).split("::")[-1]
        if nm not in SIG_SKIP:
            return nm
    return None


def exe_bodies() -> dict[int, set[tuple[str, str]]]:
    """{rva: {(tu_rel, function_name)}} for every exe-side body, channels A and B."""
    out: dict[int, set[tuple[str, str]]] = {}
    scan = S.scan_all()
    exe_tus = scan["targets"]["exe"]
    for rel, bodies in scan["bodies"].items():
        if rel not in exe_tus:
            continue
        ren = tu_renames(rel)
        lines = tu_lines(rel)
        for rva, (nm, ln) in bodies.items():
            if nm.startswith("match:"):
                nm = match_name(rel, nm[6:], rva) or nm
            nm = sig_name(lines, ln) or nm.split("::")[-1]
            out.setdefault(rva, set()).add((rel, ren.get(nm, nm)))
    # channel B: audit exe_side_copy `TU.cpp:line` -> the definition at/after that line
    idx = B.canon_tu_index()
    if B.AUDIT.exists():
        defs_cache: dict[str, dict[int, str]] = {}
        for r in csv.DictReader(B.AUDIT.open(encoding="utf-8")):
            try:
                rva = int(r["rva"].replace("0x", ""), 16)
            except ValueError:
                continue
            for tok in re.split(r"[|;,]", r.get("exe_side_copy", "") or ""):
                parts = tok.strip().replace("\\", "/").split(":")
                real = idx.get(parts[0].strip().lower())
                if not real:
                    continue
                if real not in defs_cache:
                    lines = (S.SRC / real).read_text(encoding="utf-8", errors="replace").splitlines()
                    defs_cache[real] = {ln: nm for nm, lst in S._function_defs(lines).items() for ln in lst}
                dl = defs_cache[real]
                line = int(parts[1]) if len(parts) > 1 and parts[1].strip().isdigit() else None
                nm = None
                if line is not None:
                    after = sorted(x for x in dl if x >= line)
                    if after and after[0] - line <= 3:
                        nm = dl[after[0]]
                if nm is None:
                    nm = (r.get("name") or "").split("::")[-1]
                if nm:
                    out.setdefault(rva, set()).add((real, nm))
    return out


def resolve(bodies, ents, t_lo, t_hi):
    """{rva: [(tu, name, [va...], how)]}. how = `obj` when the symbol sits in the TU's own object,
    `name` when it does not but exactly one .text symbol in the whole map has that base name (a
    body compiled under its name in another object, e.g. a MATCH wrapper's include)."""
    by_key: dict[tuple[str, str], list[int]] = {}
    by_name: dict[str, set[int]] = {}
    for va, s, _sect, obj in ents:
        b = base_name(s)
        if b:
            by_key.setdefault((obj.lower(), b), []).append(va)
            if t_lo <= va < t_hi:
                by_name.setdefault(b, set()).add(va)
    res: dict[int, list[tuple[str, str, list[int], str]]] = {}
    for rva, items in bodies.items():
        for rel, nm in sorted(items):
            obj = pathlib.PurePosixPath(rel).stem.lower() + ".obj"
            if nm.startswith("_") and (obj, nm) not in by_key:
                nm = base_name(nm)           # a MATCH line may carry the decorated C name (`_FUN_x`)
            vas = sorted(set(by_key.get((obj, nm), [])))
            how = "obj"
            if not vas and len(by_name.get(nm, ())) == 1:
                vas, how = sorted(by_name[nm]), "name"
            res.setdefault(rva, []).append((rel, nm, vas, how))
    return res, by_key


def inlined_into(rel: str, nm: str, by_key, prev, depth: int = 0) -> int | None:
    """A body with no map symbol was inlined into its callers or never emitted. The build has no
    /GL, so inlining stays inside the TU: take each line of the TU that calls `nm(` (comments
    stripped, its own definition excluded), find the definition enclosing that line, and return
    the first enclosing symbol reachable from WinMain (recursing up to 3 levels through enclosing
    functions that are themselves symbol-less)."""
    if depth > 3:
        return None
    lines = tu_lines(rel)
    defs = sorted((ln, n) for n, lst in S._function_defs(lines).items() for ln in lst)
    starts = [d for d, _n in defs]
    obj = pathlib.PurePosixPath(rel).stem.lower() + ".obj"
    ren = tu_renames(rel)
    alias = {nm} | {k for k, v in ren.items() if v == nm}       # FUN_x in a matched source = its #define name
    pat = re.compile(r"(?<![\w.>])(?:" + "|".join(map(re.escape, sorted(alias))) + r")\s*\(")
    for i, ln in enumerate(lines, 1):
        code = ln.split("//")[0]
        if not pat.search(code):
            continue
        j = bisect.bisect_right(starts, i) - 1
        if j < 0 or starts[j] == i:
            continue
        enc = defs[j][1]
        enc = ren.get(enc, enc)
        if enc == nm:
            continue
        vas = by_key.get((obj, enc), [])
        hit = [v for v in vas if v in prev]
        if hit:
            return hit[0]
        if not vas:
            r = inlined_into(rel, enc, by_key, prev, depth + 1)
            if r is not None:
                return r
    return None


def exe_file_union() -> dict[int, str]:
    """The `exe_file` value `backfill_exe_file.py` would write now, per RVA."""
    scan = S.scan_all()
    merged: dict[int, set[str]] = {}
    for rva, tus in S.rva_to_tus(scan, "exe").items():
        merged.setdefault(rva, set()).update(tus)
    for rva, tus in B.channel_b(B.canon_tu_index()).items():
        merged.setdefault(rva, set()).update(tus)
    return {rva: "|".join(sorted("mashedmod/src/mashed_re/" + t for t in v)) for rva, v in merged.items()}


# ----------------------------------------------------------------------------- hooks.csv I/O
# Every edit is byte-preserving: `port` is the LAST column and its values (none/body/called) never
# need quoting, so a record is changed only by appending `,<value>` or by replacing the text after
# its last comma. No other cell is re-serialised (a csv.writer round trip drops redundant quotes).
PORT_VALUES = ("", "none", "body", "called")
EOL = "\r\n"


def set_last(raw: str, value: str, append: bool) -> str:
    body = raw.rstrip(EOL)
    term = raw[len(body):]
    if append:
        return f"{body},{value}{term}"
    return f"{body[:body.rfind(',')]},{value}{term}"


def drop_last(raw: str) -> str:
    body = raw.rstrip(EOL)
    return body[:body.rfind(",")] + raw[len(body):]


def is_comment(i, raw, row):
    return i == 0 or not raw.strip() or raw.startswith("#") or bool(row and row[0].startswith("#"))


def owns_row(row, w, xi, pi) -> bool:
    """True when `row` is a well-formed row of the `w`-column schema whose last cell is `port`.
    The pre-existing NCOL rows (an unquoted comma in notes) can reach full width by accident: their
    shifted `exe_file` cell (notes text, not a mashedmod/ path) gives them away."""
    return (len(row) == w and row[pi] in PORT_VALUES
            and all(not t or t.startswith("mashedmod/") for t in row[xi].split("|")))


def strip_column(text: str) -> str:
    records = list(B.split_records(text))
    cols = records[0][1]
    if not cols or cols[-1] != COL:
        return text
    w, xi, pi = len(cols), cols.index(AFTER), len(cols) - 1
    out = []
    for i, (raw, row) in enumerate(records):
        if i == 0 or (not is_comment(i, raw, row) and owns_row(row, w, xi, pi)):
            out.append(drop_last(raw))
        else:
            out.append(raw)
    return "".join(out)


def port_by_rva(text: str) -> dict[str, str]:
    records = list(B.split_records(text))
    cols = records[0][1] if records else []
    if not cols or cols[-1] != COL:
        return {}
    w, xi, pi = len(cols), cols.index(AFTER), len(cols) - 1
    return {row[0].lower(): row[pi] for i, (raw, row) in enumerate(records)
            if not is_comment(i, raw, row) and owns_row(row, w, xi, pi)}


def add_column_from(text: str, ports: dict[str, str]) -> str:
    """Append `port` to a pre-`port` hooks.csv, each row's value taken from `ports` by RVA (empty
    when the RVA is not there; the next backfill run fills it). Malformed rows are left as is."""
    records = list(B.split_records(text))
    cols = records[0][1]
    if COL in cols:
        return text
    w, xi = len(cols), cols.index(AFTER)
    out = []
    for i, (raw, row) in enumerate(records):
        if i == 0:
            out.append(set_last(raw, COL, True))
        elif (not is_comment(i, raw, row) and len(row) == w
              and all(not t or t.startswith("mashedmod/") for t in row[xi].split("|"))):
            out.append(set_last(raw, ports.get(row[0].lower(), ""), True))
        else:
            out.append(raw)
    return "".join(out)


def merge_driver(o: str, a: str, b: str) -> int:
    """git merge driver for hooks.csv (`%O %A %B`; the result is written to %A).

    Every data row of a hooks.csv with `port` differs from the same row of a copy without it, so a
    plain text merge of a branch that predates the column conflicts on every row it touched. This
    driver strips `port` from all three versions, runs `git merge-file` on what is left, and puts
    `port` back (ours first, then theirs, by RVA) when either side had it. A conflict in the other
    columns is still a conflict: the markers are written to %A and the driver exits 1."""
    import subprocess
    import tempfile
    # The repo stores hooks.csv with LF and checks it out with CRLF: merge on LF, write %A's own EOL.
    raw_a = pathlib.Path(a).read_bytes()
    crlf = b"\r\n" in raw_a
    texts = [pathlib.Path(p).read_bytes().decode("utf-8").replace("\r\n", "\n") for p in (o, a, b)]
    had = any(port_by_rva(t) or (t.split("\n", 1)[0].rstrip("\r").endswith("," + COL)) for t in texts)
    ports = {**port_by_rva(texts[2]), **port_by_rva(texts[1])}
    stripped = [strip_column(t) for t in texts]
    with tempfile.TemporaryDirectory() as td:
        paths = []
        for name, t in zip(("base", "ours", "theirs"), stripped):
            p = pathlib.Path(td) / name
            p.write_bytes(t.encode("utf-8"))
            paths.append(str(p))
        r = subprocess.run(["git", "merge-file", "-p", "-L", "ours", "-L", "base", "-L", "theirs",
                            paths[1], paths[0], paths[2]], capture_output=True)
    merged = r.stdout.decode("utf-8")
    if r.returncode == 0 and had:
        merged = add_column_from(merged, ports)
    if crlf:
        merged = merged.replace("\n", "\r\n")
    pathlib.Path(a).write_bytes(merged.encode("utf-8"))
    if r.returncode != 0:
        print(f"[backfill_port --merge-driver] hooks.csv: {r.returncode} conflict(s) outside `{COL}`")
        return 1
    return 0


def stale(build: pathlib.Path) -> str | None:
    mp = build / "mashed_re.map"
    src = ROOT / "mashedmod" / "src"
    newest = max((p.stat().st_mtime, p) for p in src.rglob("*") if p.is_file())
    if newest[0] > mp.stat().st_mtime:
        return str(newest[1].relative_to(ROOT))
    return None


def main(argv) -> int:
    if "--merge-driver" in argv:
        # HB-HOOKSCSV-ROWMERGE (2026-11-10): the registered `hooksport` driver now runs the row-level
        # merge keyed by rva (scripts/hookscsv_merge.py). It covers the pre-`port` branch case too
        # (missing columns count as unchanged). The old line-based merge_driver() stays callable
        # with --merge-driver-lines.
        import hookscsv_merge
        k = argv.index("--merge-driver")
        return hookscsv_merge.driver(*argv[k + 1:k + 4])
    if "--merge-driver-lines" in argv:
        k = argv.index("--merge-driver-lines")
        return merge_driver(*argv[k + 1:k + 4])
    check = "--check" in argv
    text = CSV_PATH.read_bytes().decode("utf-8")
    if "--strip" in argv:
        new = strip_column(text)
        if new == text:
            print(f"no `{COL}` column; nothing to strip")
            return 0
        if not check:
            CSV_PATH.write_bytes(new.encode("utf-8"))
        print(f"`{COL}` column stripped" + (" (--check: not written)" if check else ""))
        return 0

    build = ROOT / "mashedmod" / "build"
    if "--build-dir" in argv:
        build = pathlib.Path(argv[argv.index("--build-dir") + 1]).resolve()
    exe, mp = build / "mashed_re.exe", build / "mashed_re.map"
    if not exe.exists() or not mp.exists():
        print(f"FATAL: {exe} / {mp} missing; build first (mashedmod\\build.bat)")
        return 1
    st = stale(build)
    if st and "--allow-stale" not in argv:
        print(f"FATAL: {mp.name} is older than {st}; rebuild first, or pass --allow-stale")
        return 1

    records = list(B.split_records(text))
    cols = records[0][1]
    if AFTER not in cols:
        print(f"FATAL: hooks.csv has no {AFTER} column")
        return 1
    added = COL not in cols
    if not added and cols[-1] != COL:
        print(f"FATAL: `{COL}` is not the last column; this script edits only a last `{COL}` column")
        return 1
    if added:
        if cols[-1] != AFTER:
            print(f"FATAL: {AFTER} is not the last column; refusing to guess where `{COL}` goes")
            return 1
        cols = cols + [COL]
    w = len(cols)
    xi, pi = cols.index(AFTER), cols.index(COL)

    ents, names_at, edges, nrel, (t_lo, t_hi) = build_graph(exe, mp)
    prev, barriers = walk(ents, names_at, edges)
    bodies = exe_bodies()
    res, by_key = resolve(bodies, ents, t_lo, t_hi)
    want_exe = exe_file_union()

    def verdict(rva: int, exe_file: str):
        if not exe_file:
            return "none", "-", ""
        items = res.get(rva, [])
        vas = [va for _r, _n, lst, _h in items for va in lst]
        if not vas:
            for r, n, _l, _h in items:
                hit = inlined_into(r, n, by_key, prev)
                if hit is not None:
                    return "called", "reached/inlined", f"0x{hit:08x} {r}:{n}"
            return "body", "unresolved", ";".join(f"{r}:{n}" for r, n, _l, _h in items)
        by = "+".join(sorted({h for _r, _n, lst, h in items if lst}))
        hit = [va for va in vas if va in prev]
        if hit:
            return "called", f"reached/{by}", f"0x{hit[0]:08x}"
        return "body", f"unreached/{by}", ";".join(f"0x{v:08x}" for v in vas)

    counts: dict[str, int] = {}
    report = []
    changes = filled_short = 0
    malformed, stale_exe = [], []
    out = []
    for i, (raw, row) in enumerate(records):
        if i == 0:
            out.append(set_last(raw, COL, True) if added else raw)
            continue
        if is_comment(i, raw, row):
            out.append(raw)
            continue
        # A data row is this script's to fill when it is a well-formed row of the current schema, or
        # one field short (a row of the pre-`port` schema, e.g. added by a branch that predates the
        # column; when this run adds the column every row is in that case).
        if len(row) == w - 1:
            row, append = row + [""], True
            filled_short += 0 if added else 1
        elif not added and owns_row(row, w, xi, pi):
            append = False
        else:
            malformed.append((i + 1, row[0] if row else "", len(row)))
            out.append(raw)
            continue
        try:
            rva = int(row[0], 16)
        except ValueError:
            out.append(raw)
            continue
        if want_exe.get(rva, "") != row[xi]:
            stale_exe.append(row[0])
        port, how, where = verdict(rva, row[xi])
        counts[port] = counts.get(port, 0) + 1
        report.append((row[0], row[2], row[3], port, how, row[xi], where))
        if not append and row[pi] == port:
            out.append(raw)
            continue
        if row[pi] != port:
            changes += 1
        out.append(set_last(raw, port, append))
    new_text = "".join(out)

    unresolved = sum(1 for r in report if r[4] == "unresolved")
    print(f"graph: {len(ents)} map symbols, {sum(len(v) for v in edges.values())} edges "
          f"({nrel} from relocations), {len(prev)} symbols reachable from WinMain, "
          f"{len(barriers)} harness barriers reached")
    print(f"exe bodies: {len(bodies)} RVAs, {sum(1 for v in res.values() if any(x[2] for x in v))} "
          f"resolved to a map symbol")
    print("port: " + "  ".join(f"{k}={counts.get(k, 0)}" for k in ("none", "body", "called")) +
          f"   (body with no map symbol: {unresolved})")
    print(f"rows changed: {changes}   short rows given the column: {filled_short}   "
          f"rows of another width left untouched: {len(malformed)}" + ("   [column added]" if added else ""))
    for rec, rva_s, width in malformed:
        print(f"WARN: record {rec} (rva {rva_s}) has {width} fields, header has {w}; left untouched")
    if stale_exe:
        print(f"FATAL: exe_file is stale on {len(stale_exe)} rows (first: {', '.join(stale_exe[:5])}); "
              f"run scripts/backfill_exe_file.py first, so `none` stays exactly `exe_file` empty")
        if "--allow-stale" not in argv:
            return 1

    if "--report" in argv:
        rp = pathlib.Path(argv[argv.index("--report") + 1])
        rp.parent.mkdir(parents=True, exist_ok=True)
        with rp.open("w", encoding="utf-8", newline="") as f:
            f.write("rva\tsubsystem\tconfidence\tport\thow\texe_file\twhere\n")
            for r in report:
                f.write("\t".join(r) + "\n")
        bp = rp.with_name(rp.stem + "_barriers.txt")
        with bp.open("w", encoding="utf-8", newline="\n") as f:
            for va in sorted(barriers):
                f.write(f"0x{va:08x}\t{';'.join(names_at.get(va, []))}\n")
        print(f"report: {rp}  barriers: {bp}")

    if check:
        print("--check: not written")
        return 0
    if new_text == text:
        print("hooks.csv already current")
        return 0
    BACKUP.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(CSV_PATH, BACKUP)
    CSV_PATH.write_bytes(new_text.encode("utf-8"))
    print(f"written; backup at {BACKUP}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
