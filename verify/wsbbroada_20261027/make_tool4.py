"""D4-WSB-C4-BROAD-A addendum 1: generate c4_racediff_v9.py from c4_racediff_v8.py.

Asserted replacements (each must match exactly once), both opt-in by env, v8 behaviour without them:
  1. C4_DEREF=1  a mapped pointer value equal to the dword at entry-arg k + off (off 0..0x7c, step 4), read at
     the moment of the call-out, is named 'A<k>@<off>' instead of by its distance from an entry arg ('A<k>+<d>')
     or its first-seen heap order ('h<n>'). Checked before the distance rule.
  2. C4_CONTROL=1  both boots run the original (MASHED_HOOK_ONLY=__none__). Verdict CONTROL-SAME when the two
     sample sets are equal and non-empty, else CONTROL-DIFF. Never C4-CLEAN.
  3. banner v8 -> v9.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "c4_racediff_v8.py"
DST = HERE / "c4_racediff_v9.py"

t = SRC.read_text(encoding="utf-8")


def rep(old, new):
    global t
    n = t.count(old)
    assert n == 1, (n, old[:80])
    t = t.replace(old, new)


# 1. field-source tokens
rep('''    if (!isMapped(v)) return v.toString(16);
''', '''    if (!isMapped(v)) return v.toString(16);
    if (DEREF_FLAG) { for (let k=0;k<ENTRY_ARGS.length;k++){ const a=ENTRY_ARGS[k]>>>0; if (a<0x10000||!isMapped(a)) continue;   // v9
        for (let o=0;o<0x80;o+=4){ let w; try{ w=ptr(a+o).readU32()>>>0; }catch(e){ break; } if (w===v) return 'A'+k+'@'+o.toString(16); } } }
''')
rep('''  const RETK = {};''', '''  const DEREF_FLAG = false;   // v9: C4_DEREF=1 sets true
  const RETK = {};''')
rep('''
def run(mode, rvas, targets, flo, fhi):''', '''
if os.environ.get("C4_DEREF") == "1": CAP = CAP.replace("const DEREF_FLAG = false;", "const DEREF_FLAG = true;")   # v9
CONTROL = os.environ.get("C4_CONTROL") == "1"   # v9
def run(mode, rvas, targets, flo, fhi):''')

# 2. control
rep('''    print("=== ON race ===");  on_s, on_jmp = run("on", rvas, targets, flo, fhi)   # bvh copy: ON first''',
    '''    if CONTROL:   # v9: original twice, first boot stands in the ON slot
        print("=== CONTROL race A (original) ===");  on_s, _ = run("off", rvas, targets, flo, fhi); on_jmp = {r: 0xe9 for r in rvas}
    else:
        print("=== ON race ===");  on_s, on_jmp = run("on", rvas, targets, flo, fhi)   # bvh copy: ON first''')
rep('''        verdict = "C4-CLEAN" if clean else "HOLD"''',
    '''        verdict = "C4-CLEAN" if clean else "HOLD"
        if CONTROL: verdict = "CONTROL-SAME" if clean else "CONTROL-DIFF"; clean = False   # v9''')

# 3. banner
rep('''    print("  bvh tool v8 scenario="''', '''    print(f"  bvh tool v9 control={CONTROL} deref={os.environ.get('C4_DEREF') == '1'} scenario="''')

DST.write_text("# D4-WSB-C4-BROAD-A v9: generated by make_tool4.py from c4_racediff_v8.py (C4_DEREF, C4_CONTROL; opt-in).\n" + t,
               encoding="utf-8")
print("wrote", DST)
