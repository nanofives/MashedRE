"""Generate worktree-safe copies of re/frida/canonical_c4_verify.py and canonical_c4_racediff.py next to this file.

Why copies: both hard-wire ORIG = <repo root>\\original (a worktree has no MASHED.exe) and write into <root>\\log, and
canonical_c4_verify.py decides `survived` from psutil, which `py -3.12` here does not have (alive is then None, so
the verdict can never be C4-READY and the spawned MASHED.exe is never killed). Logic of both tools is unchanged;
the replacements are exactly the ones below, each asserted to apply once.
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
HERE = pathlib.Path(__file__).resolve().parent
MAIN_ORIG = r'Path(r"C:\Users\maria\Desktop\Proyectos\Mashed\original")'

PSUTIL_STANDIN = '''import ctypes
class psutil:   # minimal stand-in (py -3.12 here has no psutil): True while the pid is a live process
    @staticmethod
    def pid_exists(pid):
        k = ctypes.windll.kernel32
        h = k.OpenProcess(0x1000, False, pid)          # PROCESS_QUERY_LIMITED_INFORMATION
        if not h:
            return False
        code = ctypes.c_ulong()
        k.GetExitCodeProcess(h, ctypes.byref(code)); k.CloseHandle(h)
        return code.value == 259                        # STILL_ACTIVE
'''


def rep(t, old, new):
    assert t.count(old) == 1, (old, t.count(old))
    return t.replace(old, new)


v = (ROOT / "re/frida/canonical_c4_verify.py").read_text(encoding="utf-8")
v = rep(v, "try:\n    import psutil\nexcept ImportError:\n    psutil = None\n", PSUTIL_STANDIN)
v = rep(v, 'ORIG = ROOT / "original"', "ORIG = " + MAIN_ORIG + "   # dupinstall2 copy: main install")
v = rep(v, 'LOG  = ROOT / "log"', 'LOG  = Path(os.environ.get("DUPINSTALL_OUT", str(ROOT / "log")))   # dupinstall2 copy: private dir')
v = rep(v, "        if alive: dev.kill(pid)\n", "        dev.kill(pid)    # dupinstall2 copy: always kill the pid we spawned\n")
(HERE / "c4_verify.py").write_text("# GENERATED by make_c4_tools.py from re/frida/canonical_c4_verify.py\n" + v, encoding="utf-8")

r = (ROOT / "re/frida/canonical_c4_racediff.py").read_text(encoding="utf-8")
r = rep(r, 'ORIG = ROOT / "original"; EXE = ORIG / "MASHED.exe"',
        "ORIG = " + MAIN_ORIG + "; EXE = ORIG / \"MASHED.exe\"   # dupinstall2 copy: main install")
r = rep(r, 'LOG = (ROOT / "log") if (ROOT / "log").exists() else (ROOT.parent.parent / "log")',
        'LOG = Path(os.environ.get("DUPINSTALL_OUT", str(ROOT / "log")))   # dupinstall2 copy: private dir')
r = rep(r, 'NAV = (Path(__file__).resolve().parent / "nav_agent.js").read_text(encoding="utf-8")',
        'NAV = (ROOT / "re" / "frida" / "nav_agent.js").read_text(encoding="utf-8")   # dupinstall2 copy: the repo copy')
(HERE / "c4_racediff.py").write_text("# GENERATED by make_c4_tools.py from re/frida/canonical_c4_racediff.py\n" + r, encoding="utf-8")
print("wrote c4_verify.py, c4_racediff.py")
