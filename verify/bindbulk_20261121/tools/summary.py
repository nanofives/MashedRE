"""RACE-BIND-C4-BULK: per-checkpoint tables for the RESULT.
usage (worktree root): py -3.12 verify/bindbulk_20261121/tools/summary.py <roots.tsv> <out.md>
Needs tools/last_plan.txt, tools/disposition_cp.json (bulk_bind_gen.py --write) and mashedmod/build/ddkobj/BYTECHECK.tsv
of the object build of the same tree."""
import csv, glob, json, os, re, sys
from collections import Counter, defaultdict
T = 'verify/bindbulk_20261121/tools'
roots_tsv, out_md = sys.argv[1], sys.argv[2]
roots = []
for r in csv.DictReader(open(roots_tsv, encoding='utf-8'), delimiter='\t'):
    roots.append(r['rva'][2:].lower())
rs = set(roots)
hooks = {}
for r in csv.reader(open('hooks.csv', encoding='utf-8', errors='replace')):
    if r and re.fullmatch(r'[0-9a-f]{8}', r[0]):
        hooks[r[0]] = r
plan = {}
for l in open(os.path.join(T, 'last_plan.txt'), encoding='utf-8').read().splitlines()[1:]:
    p = l.split(' ', 3)
    plan[p[0]] = (p[1], p[2] if len(p) > 2 else '')
disp = json.load(open(os.path.join(T, 'disposition_cp.json')))
refused, group, unclean = disp['refused'], disp['group'], disp['unclean']
members = {m for v in group.values() for m in v}
bc = {r['rva'][2:].lower(): r for r in csv.DictReader(open('mashedmod/build/ddkobj/BYTECHECK.tsv'), delimiter='\t')}
# new bodies = the bind wrappers this checkpoint wrote + their group members
newr = set()
for f in glob.glob('mashedmod/src/mashed_re/Match/PortTop_0*.cpp'):
    t = open(f, encoding='utf-8').read()
    if 'RACE-BIND-C4-BULK' not in t[:200]:
        continue
    newr.add(re.search(r'PortTop_([0-9a-f]{8})\.cpp', f).group(1))
newr |= members
# reachability: referenced by an exe TU other than its own wrapper and the keep-alive table
exe_tus = []
for l in open('mashedmod/exe_sources.rsp', encoding='utf-8'):
    tu = l.strip().strip('"').replace(chr(92), '/')
    if tu.endswith('.cpp') and os.path.exists('mashedmod/src/mashed_re/' + tu):
        exe_tus.append(tu)
texts = {tu: open('mashedmod/src/mashed_re/' + tu, encoding='utf-8', errors='replace').read() for tu in exe_tus}
callers = defaultdict(list)
for rva in newr:
    sym = 'PortTop_Bound_' + rva
    own = 'Match/PortTop_%s.cpp' % rva
    for tu, t in texts.items():
        if tu in (own, 'Match/PortTop_BulkRefs.cpp'):
            continue
        # a caller that is itself a wrapper written by this checkpoint is only kept alive by BulkRefs, so it does not count
        if re.search(r'\b%s\b' % sym, t) and not t.startswith('// RACE-BIND-C4-BULK'):
            callers[rva].append(tu)
res = Counter(bc[r]['result'] if r in bc else 'not-in-map' for r in newr)
lines = ['## cp tables (generated by tools/summary.py)', '',
         '- roots in list: %d' % len(roots),
         '- new bodies (wrappers + group members): %d  -> ddkobj: %s' % (len(newr), dict(res))]
reach = [r for r in sorted(newr) if callers[r]]
keep_only = [r for r in sorted(newr) if not callers[r]]
lines += ['- referenced by an exe TU other than itself / BulkRefs: %d' % len(reach),
          '- exist only through the PortTop_BulkRefs.cpp keep-alive refs: %d' % len(keep_only), '']
lines += ['### New bodies', '', '| rva | ddkobj | source | exe callers |', '|---|---|---|---|']
for r in sorted(newr):
    b = bc.get(r)
    lines.append('| 0x%s | %s | %s | %s |' % (r, b['result'] if b else 'not-in-map', b['src'] if b else '', ', '.join(c.replace('Match/', '') for c in callers[r][:3]) or 'keep-alive only'))
# dispositions of every root
dispo = {}
for r in roots:
    k, why = plan.get(r, ('?', ''))
    if r in newr:
        dispo[r] = ('bound', 'new body')
    elif r in unclean:
        dispo[r] = ('unbound', 'cpp-unclean: ' + unclean[r][:40])
    elif r in refused:
        dispo[r] = ('unbound', refused[r][:80])
    elif k == 'reuse':
        dispo[r] = ('already', 'exe body existed before (%s)' % why.split(' ')[0])
    elif k == 'stop':
        dispo[r] = ('stop', why)
    else:
        dispo[r] = ('?', k)
cnt = Counter(v[0] for v in dispo.values())
lines += ['', '### Disposition of the %d listed rvas' % len(roots), '', str(dict(cnt)), '']
def cls(r):
    h = hooks.get(r)
    n = (h[8] if h else '') + ' ' + (h[2] if h else '') + ' ' + (h[1] if h else '')
    if 'frida-replay' in n and 'libid' not in n:
        return 'frida-replay, no re/match source (hand .asi body only)'
    if 'libid' in n:
        if re.search(r'directshow|CBase|strmbase|renbase|amfilter|wxutil|ctlutil', n, re.I):
            return 'libid DirectShow base classes'
        if re.search(r'd3dx|crt|libc|msvcrt|CRT', n, re.I):
            return 'libid d3dx or CRT'
        return 'libid other (%s)' % (h[2] if h else '?')
    if 'c4=match' in n:
        return 'c4=match with no usable source'
    return 'untagged / other'
st = defaultdict(list)
for r, (k, why) in dispo.items():
    if k == 'stop':
        st[cls(r)].append(r)
lines += ['### In-list stops (no body bound), by C4 route and subsystem', '', '| class | count | subsystems |', '|---|---|---|']
for c, rv in sorted(st.items(), key=lambda x: -len(x[1])):
    sub = Counter(hooks[r][2] if r in hooks else '?' for r in rv)
    lines.append('| %s | %d | %s |' % (c, len(rv), '; '.join('%s x%d' % (a, b) for a, b in sub.most_common(4))))
lines += ['', '### Unbound listed rvas with a reason', '', '| rva | name | reason |', '|---|---|---|']
for r in roots:
    if dispo[r][0] == 'unbound':
        lines.append('| 0x%s | %s | %s |' % (r, hooks[r][1] if r in hooks else '', dispo[r][1]))
lines += ['', '### Listed rvas already carried / bound before this checkpoint', '', '| rva | name | note |', '|---|---|---|']
for r in roots:
    if dispo[r][0] == 'already':
        lines.append('| 0x%s | %s | %s |' % (r, hooks[r][1] if r in hooks else '', dispo[r][1]))
open(out_md, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('\n'.join(lines[:16]))
