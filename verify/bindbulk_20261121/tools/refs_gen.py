"""RACE-BIND-C4-BULK: write Match/PortTop_BulkRefs.cpp, a TU of linker /include pragmas, one per bulk-bound body, so the
exe link (and with it the object build's byte check) keeps every pre-bound unit although no exe code calls it yet
(without a reference /OPT:REF drops it and ddkobj.py check reports it not-in-map). Each pragma names the
PortTop_Keep_<rva> anchor the wrapper defines (extern "C" data, so its decoration is always _PortTop_Keep_<rva>).
usage (worktree root): py -3.12 verify/bindbulk_20261121/tools/refs_gen.py
Reads tools/disposition_cp*.json 'keep' lists (written by bulk_bind_gen.py), writes the file."""
import glob, json, os
T = 'verify/bindbulk_20261121/tools'
keep = set()
for p in glob.glob(os.path.join(T, 'disposition_cp*.json')):
    keep |= set(json.load(open(p))['keep'])
L = ['// generated by verify/bindbulk_20261121/tools/refs_gen.py, to be owned by porttop_bind.py (BIND-CUNCLEAN-AS-C); do not edit by hand',
     '// RACE-BIND-C4-BULK (2026-11-21): keeps every pre-bound body linked in the exe. No code calls these bodies yet; each',
     '// /include keeps its PortTop_Keep_<rva> anchor (and so the body) out of /OPT:REF so the object build byte-checks the',
     '// unit. A unit leaves this list once a bound caller references it. Never run.',
     '// RVA-LINT: ORIGTOP-ONLY', '#ifdef MASHED_STANDALONE']
L += ['#pragma comment(linker, "/include:_PortTop_Keep_%s")' % c for c in sorted(keep)]
L.append('#endif // MASHED_STANDALONE')
out = 'mashedmod/src/mashed_re/Match/PortTop_BulkRefs.cpp'
open(out, 'w', newline='\n').write('\n'.join(L) + '\n')
print('refs', len(keep), '->', out)
