"""PORT-OT-SEED-CODEPTR: the code-pointer entries PORT-OT-SEED-2 left out (SEED2_ADDED.tsv action=code-pointer).

For each entry, read the original's file-backed dwords (MASHED.exe.unpatched) from the entry address on: the entry's
own size, extended while the next dword still points into .text and no other inventory label starts there. Each
dword that points into .text becomes one fix-up slot (slot address, original target). Each target is resolved to
the exe symbol that BINDINGS.tsv records for it (kind matched / bound / rw ...), else to a stop thunk.

usage: py -3.12 verify/portorigtop_20261109/codeptr_inventory.py [--write]
  --write: CODEPTR_SLOTS.tsv here and mashedmod/src/mashed_re/Compat/PortTopCodePtr.inc
"""
import csv, os, sys
import pefile

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
EXE = os.environ.get('MASHED_UNPATCHED', r'C:\Users\maria\Desktop\Proyectos\Mashed\original\MASHED.exe.unpatched')
INV = os.path.join(HERE, 'SEED2_ADDED.tsv')
BIND = os.path.join(ROOT, 'verify', 'porttop_20261108', 'BINDINGS.tsv')
FUNCS = os.path.join(ROOT, 're', 'console', 'pc_funcs.csv')
OUT_TSV = os.path.join(HERE, 'CODEPTR_SLOTS.tsv')
OUT_INC = os.path.join(ROOT, 'mashedmod', 'src', 'mashed_re', 'Compat', 'PortTopCodePtr.inc')
MAX_EXTEND = 64  # dwords past the entry's own size


def main():
    pe = pefile.PE(EXE, fast_load=True)
    base = pe.OPTIONAL_HEADER.ImageBase
    text = next(s for s in pe.sections if s.Name.rstrip(b'\0') == b'.text')
    t0, t1 = base + text.VirtualAddress, base + text.VirtualAddress + text.Misc_VirtualSize

    def dword(va):
        return pe.get_dword_at_rva(va - base)

    def file_backed(va):
        for s in pe.sections:
            lo = base + s.VirtualAddress
            if lo <= va < lo + s.SizeOfRawData and va + 4 <= lo + s.SizeOfRawData:
                return True
        return False

    entries = [r for r in csv.DictReader(open(INV, encoding='utf-8'), delimiter='\t')]
    labels = {int(r['addr'], 16) for r in entries}
    cp = [r for r in entries if r['action'] == 'code-pointer']
    funcs = {int(r['entry'], 16): r['name'] for r in csv.DictReader(open(FUNCS, encoding='utf-8'))}
    bind = {}
    for r in csv.DictReader(open(BIND, encoding='utf-8'), delimiter='\t'):
        bind[int(r['rva'], 16)] = (r['kind'], r['exe_symbol'])

    slots = []  # (entry, slot, target, size_note)
    for r in cp:
        a, n = int(r['addr'], 16), int(r['size'])
        va, end = a, a + n
        while True:
            if va >= end:
                if va - (a + n) >= MAX_EXTEND * 4 or va in labels or not file_backed(va):
                    break
                v = dword(va)
                if not (t0 <= v < t1):
                    break
            if not file_backed(va):
                break
            v = dword(va)
            if t0 <= v < t1:
                slots.append((a, va, v, r['rows']))
            va += 4
    # Non-code dwords inside an entry's own size are data: seeded with the original bytes. A dword that points at a
    # NUL-terminated printable string in a file-backed section carries the string too (as PORT-OT-SEED-2 did).
    seeds = []  # (va, bytes, why)
    code_slots = {s for _, s, _, _ in slots}
    for r in cp:
        a, n = int(r['addr'], 16), int(r['size'])
        for va in range(a, a + n, 4):
            if va in code_slots or not file_backed(va):
                continue
            v = dword(va)
            seeds.append((va, pe.get_data(va - base, 4), 'data dword in 0x%08x' % a))
            if file_backed(v) and not (t0 <= v < t1):
                raw = pe.get_data(v - base, 256)
                z = raw.find(b'\0')
                if z > 0 and all(32 <= c < 127 for c in raw[:z]):
                    seeds.append((v, raw[:z + 1], 'string at 0x%08x' % va))
    seen, rows = set(), []
    for a, s, v, users in slots:
        if s in seen:
            continue
        seen.add(s)
        kind, sym = bind.get(v, ('', ''))
        rows.append((a, s, v, funcs.get(v, ''), kind, sym, users))
    print('entries', len(cp), 'slots', len(rows), 'distinct targets', len({r[2] for r in rows}))
    for r in rows:
        print('0x%08x 0x%08x -> 0x%08x %-14s %-10s %s' % (r[0], r[1], r[2], r[3] or 'LAB', r[4], r[5]))
    if '--write' in sys.argv:
        with open(OUT_TSV, 'w', encoding='utf-8', newline='\n') as f:
            f.write('entry\tslot\ttarget\ttarget_name\tbind_kind\texe_symbol\treading_rows\n')
            for r in rows:
                f.write('0x%08x\t0x%08x\t0x%08x\t%s\t%s\t%s\t%s\n' % (r[0], r[1], r[2], r[3] or 'LAB_%08x' % r[2], r[4], r[5], r[6]))
        print('wrote', OUT_TSV)
        stops = sorted({r[2] for r in rows if not r[5]})
        syms = sorted({r[5] for r in rows if r[5]})
        L = ['// GENERATED by verify/portorigtop_20261109/codeptr_inventory.py --write (PORT-OT-SEED-CODEPTR). Do not edit.',
             '// The 22 code-pointer entries PORT-OT-SEED-2 left out (SEED2_ADDED.tsv action=code-pointer), expanded to every',
             '// dword of the original (MASHED.exe.unpatched) that points into .text: %d slots, %d distinct targets.' % (len(rows), len({r[2] for r in rows})),
             '// CP_FIX(slot, exe symbol, original target): %d slots bound to an exe body named in BINDINGS.tsv, %d to a stop'
             % (sum(1 for r in rows if r[5]), sum(1 for r in rows if not r[5])),
             '// thunk (no exe body: logs the target and ends the process). CP_SEED(va, len, bytes): %d data blocks inside the'
             % len(seeds),
             '// entries (non-code dwords, and the strings they point at). Consumer: Compat/PortTopCodePtr.cpp, MASHED_ORIG_TOP only.',
             '#define PORTTOP_CODEPTR_SLOTS %d' % len(rows),
             '#define PORTTOP_CODEPTR_SEEDS %d' % len(seeds)]
        L.append('#ifdef CP_EXTERN')
        L += ['CP_EXTERN(%s)' % s for s in syms]
        L.append('#endif')
        L.append('#ifdef CP_STOP')
        L += ['CP_STOP(0x%08x, %s)' % (t, 'PortTopCodePtr_Stop_%08x' % t) for t in stops]
        L.append('#endif')
        L.append('#ifdef CP_FIX')
        for r in rows:
            L.append('CP_FIX(0x%08x, %s, 0x%08x)   // entry 0x%08x, %s'
                     % (r[1], r[5] or 'PortTopCodePtr_Stop_%08x' % r[2], r[2], r[0], r[3] or 'LAB_%08x' % r[2]))
        L.append('#endif')
        L.append('#ifdef CP_SEED')
        for va, b, why in seeds:
            L.append('CP_SEED(0x%08x, %d, "%s")   // %s' % (va, len(b), ''.join('\\x%02x' % c for c in b), why))
        L.append('#endif')
        with open(OUT_INC, 'w', encoding='utf-8', newline='\n') as f:
            f.write('\n'.join(L) + '\n')
        print('wrote', OUT_INC, 'seeds', len(seeds), 'stops', len(stops), 'syms', syms)


if __name__ == '__main__':
    main()
