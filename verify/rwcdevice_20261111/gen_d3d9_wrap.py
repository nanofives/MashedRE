"""RWC-DEVICE: generate the plain forwarding members of the in-exe IDirect3D9 / IDirect3DDevice9 wrapper.

Reads the IDirect3D9 and IDirect3DDevice9 interface blocks of the Windows SDK d3d9.h and writes one .inc per
interface: every method becomes an inline member that forwards to m_real, except the methods named in HAND (the
wrapper TU writes those itself). The vtable order is the header's declaration order, so the wrapper's vtable has
the same slots as the real interface (IDirect3D9::CreateDevice = slot 16, IDirect3DDevice9::Present = slot 17).

    py -3.12 verify/rwcdevice_20261111/gen_d3d9_wrap.py [--sdk <path to d3d9.h>]

Output: mashedmod/src/mashed_re/Compat/D3d9Wrap_IDirect3D9.inc, D3d9Wrap_IDirect3DDevice9.inc.
"""
import argparse
import pathlib
import re
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[1]
OUT = ROOT / "mashedmod" / "src" / "mashed_re" / "Compat"
DEFAULT_SDK = pathlib.Path(r"C:\Program Files (x86)\Windows Kits\10\Include\10.0.26100.0\shared\d3d9.h")

HAND = {
    "IDirect3D9": {"QueryInterface", "AddRef", "Release", "CreateDevice"},
    "IDirect3DDevice9": {"QueryInterface", "AddRef", "Release", "GetDirect3D", "Present", "Reset"},
}

METHOD = re.compile(r"^\s*STDMETHOD(?:_\(\s*([^,]+?)\s*,\s*(\w+)\s*\)|\((\w+)\))\s*\(\s*(THIS_?)\s*(.*?)\)\s*PURE\s*;")


def block(text, name):
    m = re.search(r"DECLARE_INTERFACE_\(%s,\s*IUnknown\)\s*\{(.*?)\n\};" % name, text, re.S)
    if not m:
        sys.exit("no interface block for " + name)
    return m.group(1)


def name_params(params):
    """(declaration text, argument names). The header leaves some parameters unnamed (`D3DTRANSFORMSTATETYPE,
    CONST D3DMATRIX*`): those get the names a0, a1, ..."""
    if not params.strip():
        return "", []
    decls, names = [], []
    for i, p in enumerate(params.split(",")):
        p = p.strip()
        ids = [t for t in re.findall(r"[A-Za-z_]\w*", p) if t not in ("CONST", "const")]
        if not ids:
            sys.exit("cannot name parameter: " + p)
        if len(ids) == 1:
            n = "a%d" % i
            decls.append("%s %s" % (p, n))
            names.append(n)
        else:
            decls.append(p)
            names.append(ids[-1])
    return ",".join(decls), names


def gen(text, name):
    lines = []
    slot = 0
    for raw in block(text, name).splitlines():
        m = METHOD.match(raw)
        if not m:
            continue
        ret, mname, plain, _this, params = m.groups()
        mname = mname or plain
        ret = ret or "HRESULT"
        if mname not in HAND[name]:
            decl, names = name_params(params)
            call = "m_real->%s(%s)" % (mname, ", ".join(names))
            body = ("%s; " % call) if ret.strip() == "void" else ("return %s; " % call)
            lines.append("    /* slot %3d */ %s STDMETHODCALLTYPE %s(%s) override { %s}"
                         % (slot, ret, mname, decl, body))
        else:
            lines.append("    /* slot %3d */ // %s: written by hand in D3d9Wrap.cpp" % (slot, mname))
        slot += 1
    head = ("// GENERATED by verify/rwcdevice_20261111/gen_d3d9_wrap.py from the Windows SDK d3d9.h (%s). Do not edit.\n"
            "// %s: %d methods in vtable order; plain members forward to m_real.\n" % (name, name, slot))
    return head + "\n".join(lines) + "\n", slot


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sdk", default=str(DEFAULT_SDK))
    a = ap.parse_args()
    text = pathlib.Path(a.sdk).read_text(encoding="latin-1")
    for name in ("IDirect3D9", "IDirect3DDevice9"):
        body, n = gen(text, name)
        out = OUT / ("D3d9Wrap_%s.inc" % name)
        out.write_text(body, encoding="ascii", newline="\n")
        print("%s: %d methods -> %s" % (name, n, out.relative_to(ROOT)))


if __name__ == "__main__":
    main()
