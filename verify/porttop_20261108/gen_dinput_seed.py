"""PORT-TOP-04A: .rdata seed for the DirectInput objects the original's gate chain reads (MASHED_ORIG_TOP only).

The exe maps the original data range zero-filled. 0x00495530 passes &DAT_005d0a8c (IID) to DirectInput8Create, and
0x00496320 passes DAT_005d09ec (GUID) to CreateDevice and DAT_005d0974 (a 24-byte DIDATAFORMAT) to SetDataFormat.
The DIDATAFORMAT points (+0x14) at an array of +0x10 DIOBJECTDATAFORMAT entries (16 bytes each), whose first dword
points at a GUID or is 0. All of these live in the original image, so writing their original bytes back at the same
addresses makes every pointer in them valid. Bytes come from original/MASHED.exe.unpatched (anchor checked).

usage: py -3.12 verify/porttop_20261108/gen_dinput_seed.py
"""
import hashlib
import os
import struct
import sys

import pefile

ROOT = os.environ.get('MASHED_ROOT', r'C:\Users\maria\Desktop\Proyectos\Mashed')
BIN = os.path.join(ROOT, 'original', 'MASHED.exe.unpatched')
ANCHOR = 'BDCAE093A30FBF226BDD852B9C36798A987AEE33B3AE82BF7404B0336EFD3C0E'
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'mashedmod', 'src', 'mashed_re', 'Match',
                   'PortTop_DInputSeed.inc')


def main():
    data = open(BIN, 'rb').read()
    if hashlib.sha256(data).hexdigest().upper() != ANCHOR:
        sys.exit('anchor mismatch: ' + BIN)
    pe = pefile.PE(data=data, fast_load=True)
    base = pe.OPTIONAL_HEADER.ImageBase

    def rd(va, n):
        return pe.get_data(va - base, n)

    ranges = {}

    def add(va, n, why):
        ranges[va] = (n, why)

    add(0x005d0a8c, 16, 'IID passed to DirectInput8Create by 0x00495530')
    add(0x005d09ec, 16, 'GUID passed to CreateDevice by 0x00496320')
    add(0x005d0974, 24, 'DIDATAFORMAT passed to SetDataFormat by 0x00496320')
    # The DIDATAFORMAT itself is NOT seeded: its object array (+0x14) sits at 0x0049b5d0, inside the original code
    # range, which the exe does not map as original data. Match/PortTop_InputPort.cpp copies the exe's own
    # c_dfDIKeyboard (dinput8.lib) to 0x005d0974 instead, after checking it against this header.
    del ranges[0x005d0974]
    hdr = rd(0x005d0974, 20)
    lines = ['// GENERATED by verify/porttop_20261108/gen_dinput_seed.py from original/MASHED.exe.unpatched (anchor ' +
             ANCHOR[:16] + '...). Do not edit.',
             '// { original VA, byte count, bytes } for the DirectInput GUIDs and keyboard data format of 0x00495530 /'
             ' 0x00496320.']
    for va in sorted(ranges):
        n, why = ranges[va]
        b = rd(va, n)
        lines.append('{ 0x%08xu, %d, "%s" },  // %s' % (va, n, ''.join('\\x%02x' % c for c in b), why))
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote %d ranges, %d bytes -> %s' % (len(ranges), sum(v[0] for v in ranges.values()), OUT))


if __name__ == '__main__':
    main()
