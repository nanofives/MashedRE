"""PORT-TOP-02: generate the .rdata string seed for the MASHED_ORIG_TOP knob path.

The exe maps the original data range zero-filled (exe_main.cpp g_b17_low_arena_pad), so a matched body that reads an
original string (MGLOBALA(char, s_..., N, 0x...)) reads zeros there. Under the knob only, Match/PortTop_00492370.cpp
writes the original bytes back to those addresses before the matched WinMain runs. This script reads them from the
anchored, unpatched binary (original/MASHED.exe.unpatched, SHA-256 BDCAE093...) and writes
mashedmod/src/mashed_re/Match/PortTop_RdataSeed.inc.

usage: py -3.12 verify/porttop_20261108/gen_rdata_seed.py <match source>...
"""
import hashlib
import os
import re
import sys

import pefile

ROOT = os.environ.get('MASHED_ROOT', r'C:\Users\maria\Desktop\Proyectos\Mashed')
BIN = os.path.join(ROOT, 'original', 'MASHED.exe.unpatched')
ANCHOR = 'BDCAE093A30FBF226BDD852B9C36798A987AEE33B3AE82BF7404B0336EFD3C0E'
OUT = os.path.join(os.path.dirname(__file__), '..', '..', 'mashedmod', 'src', 'mashed_re', 'Match',
                   'PortTop_RdataSeed.inc')
PAT = re.compile(r'MGLOBALA\(char,\s*(s_\w+),\s*(\w+),\s*(0x[0-9a-fA-F]+)\)')
# PORT-TOP-04F: a single-char global the source passes by address as a string (re/match/s06/004283a0.c
# MGLOBAL(char, DAT_005cd640, 0x005cd640) = "bigE"). Seeded up to and including its NUL, and only when the address
# lies in a section that is not writable (a string constant, not a variable).
PAT1 = re.compile(r'MGLOBAL\(char,\s*(\w+),\s*(0x[0-9a-fA-F]+)\)')
# PORT-TOP-04G: a pointer-typed global whose ADDRESS the source passes as a string (re/match/s14/0048bbe0.c
# MGLOBAL(void *, PTR_DAT_005cf4a8, 0x005cf4a8) passed as &PTR_DAT_005cf4a8 = "sun"). Same rule as PAT1 (read-only
# section, up to and including the NUL), and only when "&<name>" appears in the source.
PAT2 = re.compile(r'MGLOBAL\(void \*,\s*(\w+),\s*(0x[0-9a-fA-F]+)\)')
IMAGE_SCN_MEM_WRITE = 0x80000000


def main(srcs):
    data = open(BIN, 'rb').read()
    if hashlib.sha256(data).hexdigest().upper() != ANCHOR:
        sys.exit('anchor mismatch: ' + BIN)
    pe = pefile.PE(data=data, fast_load=True)
    base = pe.OPTIONAL_HEADER.ImageBase
    rows = {}
    for s in srcs:
        for name, n, addr in PAT.findall(open(s, encoding='utf-8').read()):
            rows[int(addr, 16)] = (name, int(n, 0), os.path.basename(s))
        text = open(s, encoding='utf-8').read()
        pairs = PAT1.findall(text) + [(n, a) for n, a in PAT2.findall(text) if re.search(r'&\s*' + n + r'\b', text)]
        for name, addr in pairs:
            va = int(addr, 16)
            sec = next((x for x in pe.sections
                        if x.VirtualAddress <= va - base < x.VirtualAddress + x.Misc_VirtualSize), None)
            if sec is None or sec.Characteristics & IMAGE_SCN_MEM_WRITE:
                continue
            off = pe.get_offset_from_rva(va - base)
            rows[va] = (name, data.index(bytes(1), off) - off + 1, os.path.basename(s))
    lines = ['// GENERATED by verify/porttop_20261108/gen_rdata_seed.py from original/MASHED.exe.unpatched (anchor ' +
             ANCHOR[:16] + '...). Do not edit.',
             '// { original VA, byte count, bytes } for the strings the MASHED_ORIG_TOP knob path\'s matched bodies read.']
    for va in sorted(rows):
        name, n, src = rows[va]
        off = pe.get_offset_from_rva(va - base)
        b = data[off:off + n]
        lit = ''.join('\\x%02x' % c for c in b)
        lines.append('{ 0x%08xu, %d, "%s" },  // %s (%s) %r' % (va, n, lit, name, src, b.rstrip(b'\0').decode('latin-1')))
    open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('wrote %d rows -> %s' % (len(rows), os.path.normpath(OUT)))


if __name__ == '__main__':
    main(sys.argv[1:])
