TEMPLATE = '''// PORT-TOP-04A (L-96 top-down lane): exe-only port body of rva 0x{rva} = the matched source re/match/{src}
// ({what}). Generated by verify/porttop_20261108/gen_top04a_tus.py. Reached only on the MASHED_ORIG_TOP path
// (WinMain 0x00492370 -> 0x00493540 / 0x00493560). Callees bind by name; no raw-address call.
#ifdef MASHED_STANDALONE
#include "../Core/HookSystem.h"

#define MATCH_PORT 1
#define FUN_{rva} {sym}
{binds}
extern "C" {{
#include "../../../../re/match/{src}"
}}
#endif // MASHED_STANDALONE
'''


def main():
    for rva, (src, sym, what, binds) in TUS.items():
        b = '\n'.join('#define %s %s   // %s' % (n, s, c) for n, s, c in binds)
        txt = TEMPLATE.format(rva=rva, src=src, what=what, sym=sym, binds=b)
        if rva == '00496010':
            # The source declares FUN_004b6520(undefined4, undefined4) and passes &DAT_00771e88 (C accepts it, C++ does
            # not). A C++-linkage overload taking the pointer is the one the call resolves to; the C-linkage
            # declaration from the source is never called or defined.
            nl = chr(10)
            txt = txt.replace('extern "C" {', 'extern "C" void __cdecl ZeroFillWrapper(void* p, unsigned int n);   // Util/TimerSlot.cpp' + nl +
                              'static void PortTop_ZeroFill_00496010(unsigned int* p, int n) { ZeroFillWrapper(p, static_cast<unsigned int>(n)); }' + nl +
                              'extern "C" {', 1)
        open(os.path.join(MATCH, 'PortTop_%s.cpp' % rva), 'w', encoding='utf-8', newline='\n').write(txt)
        print('PortTop_%s.cpp' % rva)


if __name__ == '__main__':
    main()
