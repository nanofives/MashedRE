"""Transcribe FUN_00404830 @ 0x00404830 (dirt-texture index tables) from its decompilation into
C++ and into Python, mechanically, so no value is hand-copied.

    py -3.12 gen_dirt_tables.py <decomp of FUN_00404830> <out.inc>

The decompilation (evidence/decomp_rtex.txt, FUN_00404830) is: fill DAT_00639cc8[0x28] and
DAT_00636c08[0xc30] with -1, a run of absolute stores into DAT_00639cc8, then a 6-pass loop
`puVar1 = &DAT_006390b0; do { puVar1[N] = V; ... puVar1 = puVar1 + 1; } while (puVar1 < 0x6390c8)`
into DAT_00636c08. The .inc holds the stores as C++ statements on `body` / `wheel`; the
script also prints the TRAINING (course 30) / Arctic (0) / City (26) entries as a check.
"""
import re
import sys

BODY, WHEEL = 0x00639cc8, 0x00636c08
src = open(sys.argv[1], encoding="utf-8").read()
fn = src[src.index("void FUN_00404830"):]
fn = fn[:fn.index("\n}\n") + 3] if "\n}\n" in fn else fn
body_stores = []
for m in re.finditer(r"_?DAT_([0-9a-f]{8}) = (0x[0-9a-f]+|-?\d+);", fn):
    addr, v = int(m.group(1), 16), int(m.group(2), 0)
    assert BODY <= addr < BODY + 0x28 * 4, hex(addr)
    body_stores.append(((addr - BODY) // 4, v, addr))
loop = fn[fn.index("puVar1 = &DAT_006390b0;"):]
loop_stores = [(int(n, 0), int(v, 0)) for n, v in re.findall(r"puVar1\[(-?(?:0x[0-9a-f]+|\d+))\] = (0x[0-9a-f]+|\d+);", loop)]
loop_stores += [(0, int(v, 0)) for v in re.findall(r"\*puVar1 = (0x[0-9a-f]+|\d+);", loop)]
start = (0x006390b0 - WHEEL) // 4
assert re.search(r"while \(\(int\)puVar1 < 0x6390c8\)", loop)
passes = (0x6390c8 - 0x006390b0) // 4

body = [-1] * 0x28
wheel = [-1] * 0xc30
for i, v, a in body_stores:
    body[i] = v
for k in range(passes):
    for n, v in loop_stores:
        wheel[start + k + n] = v

with open(sys.argv[2], "w", newline="\n") as f:
    f.write("// GENERATED by verify/rtex_20261016/gen_dirt_tables.py from the decompilation of\n"
            "// FUN_00404830 @ 0x00404830. Do not edit by hand.\n")
    for i, v, a in body_stores:
        f.write(f"body[0x{i:02x}] = {v};   // 0x{a:08x}\n")
    f.write(f"for (int k = 0; k < {passes}; ++k) {{   // puVar1 = &DAT_006390b0 .. < 0x006390c8\n")
    f.write(f"    std::int32_t* p = wheel + 0x{start:x} + k;\n")
    for n, v in loop_stores:
        f.write(f"    p[{n}] = {v};\n")
    f.write("}\n")
print(f"body stores {len(body_stores)}, loop stores {len(loop_stores)} x {passes} passes")
for course in (30, 0, 26):
    print(f"course {course}: body {body[course]}  wheel[veh 6..11] {wheel[course * 0x4e + 6:course * 0x4e + 12]}")
