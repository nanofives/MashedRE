"""BIND-CRT-HELPERS: write orig_helpers.h = the six helper bodies copied from MASHED.exe.unpatched (Ghidra sizes), for
helper_test.cpp to run in place. All six are self-contained (no absolute address, checked with capstone in the RESULT).
usage: py -3.12 verify/bindcrthelpers_20261111/gen_orig.py
"""
import pathlib, sys
HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[1] / 're' / 'tools' / 'match'))
import match as M

ROWS = [('ftol2', 0x004a2c48), ('alldiv', 0x004a4170), ('allmul', 0x004a4220), ('aulldiv', 0x004a4e40),
        ('aullrem', 0x004aa060), ('chkstk', 0x004a3440)]
out = ['// generated by gen_orig.py from original/MASHED.exe.unpatched', '#pragma once']
for name, a in ROWS:
    b = M.original_bytes(a, M.ghidra_size(a))
    out.append('static const unsigned char k_orig_%s[%d] = {  // 0x%08x' % (name, len(b), a))
    for i in range(0, len(b), 16):
        out.append('    ' + ', '.join('0x%02x' % x for x in b[i:i + 16]) + ',')
    out.append('};')
(HERE / 'orig_helpers.h').write_text('\n'.join(out) + '\n', encoding='utf-8')
print('wrote', HERE / 'orig_helpers.h')
